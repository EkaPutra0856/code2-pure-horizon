UAnimMontage* ABFPlayerCharacter::PlayAnim(UAnimSequence* Anim, float Rate, float BlendIn, float BlendOut, int32 LoopCount)
{
	UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
	if (!Anim || !AnimInstance)
	{
		return nullptr;
	}
	// Inertial blends with a floor on their length: short linear crossfades read as skipped frames.
	const float In = FMath::Max(BlendIn, 0.12f);
	const float Out = BlendOut <= 0.f ? 0.f : FMath::Max(BlendOut, 0.3f);
	CurrentMontage = AnimInstance->PlaySlotAnimationAsDynamicMontage_WithBlendSettings(Anim, TEXT("DefaultSlot"), BFAnimBlend::Inert(In), BFAnimBlend::Inert(Out), Rate, LoopCount);
	return CurrentMontage;
}

void ABFPlayerCharacter::HoldLastFrame()
{
	// The auto-blend-out switch lives on the montage *instance* (copied from the asset when it starts
	// playing), so setting it on the asset afterwards did nothing: the clip blended back to the
	// standing idle at its end - the body "stood up" for a moment before the get-up.
	if (!CurrentMontage)
	{
		return;
	}
	CurrentMontage->bEnableAutoBlendOut = false;
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		if (FAnimMontageInstance* Instance = AnimInstance->GetActiveInstanceForMontage(CurrentMontage))
		{
			Instance->bEnableAutoBlendOut = false;
		}
	}
}

void ABFPlayerCharacter::StartKnockdown(UAnimSequence* Anim, float LieTime)
{
	const float Len = Anim ? Anim->GetPlayLength() : 1.f;
	StartStun(Len + LieTime, Anim, 1.f);
	HoldLastFrame();
	bKnockedDown = true;
	DownLoopAt = GetWorld()->GetRealTimeSeconds() + Len - 0.05;
}

ABFEnemyBase* ABFPlayerCharacter::FindSoftLockTarget(float Range) const
{
	ABFEnemyBase* Best = nullptr;
	float BestDistSq = Range * Range;
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		if (It->IsDead())
		{
			continue;
		}
		const float DistSq = FVector::DistSquared2D(It->GetActorLocation(), GetActorLocation());
		if (DistSq < BestDistSq)
		{
			BestDistSq = DistSq;
			Best = *It;
		}
	}
	return Best;
}

void ABFPlayerCharacter::FaceForAction()
{
	FVector Dir = FVector::ZeroVector;
	if (const ABFEnemyBase* Target = GetFacingTarget(700.f))
	{
		Dir = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
	}
	else if (HasRecentMoveInput())
	{
		Dir = LastMoveInput;
	}
	if (!Dir.IsNearlyZero())
	{
		SetActorRotation(FRotator(0.f, Dir.Rotation().Yaw, 0.f));
	}
}

void ABFPlayerCharacter::StartAttack(EBFChain Chain, int32 Index)
{
	const TArray<FBFAttackDef>& Defs = GetChainDefs(Chain);
	const TArray<TObjectPtr<UAnimSequence>>& Anims = GetChainAnims(Chain);
	if (!Defs.IsValidIndex(Index) || !Anims.IsValidIndex(Index) || !Anims[Index])
	{
		return;
	}

	FaceForAction();
	if (!PlayAnim(Anims[Index], Defs[Index].PlayRate, 0.06f, 0.3f))
	{
		return;
	}

	State = EBFPlayerState::Attacking;
	CurrentChain = Chain;
	ComboIndex = Index;
	ActiveWindow = INDEX_NONE;
	Buffered = EBuffered::None;
	bInvulnerable = false;
}

void ABFPlayerCharacter::GetBladePoints(TArray<FVector>& OutPoints) const
{
	const FTransform& X = Sword->GetComponentTransform();
	const FVector A = X.TransformPosition(BladeLocalA);
	const FVector B = X.TransformPosition(BladeLocalB);
	constexpr int32 NumPoints = 5;
	OutPoints.SetNum(NumPoints);
	for (int32 i = 0; i < NumPoints; ++i)
	{
		OutPoints[i] = FMath::Lerp(A, B, float(i) / float(NumPoints - 1));
	}
}

void ABFPlayerCharacter::SweepBlade(bool bFirstFrame)
{
	TArray<FVector> Points;
	GetBladePoints(Points);
	if (bFirstFrame || PrevBladePoints.Num() != Points.Num())
	{
		PrevBladePoints = Points;
	}

	FCollisionObjectQueryParams ObjectParams(ECC_Pawn);
	FCollisionQueryParams Params(SCENE_QUERY_STAT(BFBladeSweep), false, this);
	const FCollisionShape Shape = FCollisionShape::MakeSphere(12.f);

	TArray<FHitResult> Hits;
	auto Consider = [this](const TArray<FHitResult>& Results)
	{
		for (const FHitResult& Hit : Results)
		{
			ABFEnemyBase* Enemy = Cast<ABFEnemyBase>(Hit.GetActor());
			if (!Enemy || Enemy->IsDead() || HitThisWindow.Contains(Enemy))
			{
				continue;
			}
			HitThisWindow.Add(Enemy);
			const FVector Impact = Hit.bStartPenetrating ? FVector(Hit.TraceStart) : FVector(Hit.ImpactPoint);
			ApplyWeaponHit(Enemy, Impact);
		}
	};

	// Sweep each blade sample along its motion since last frame, plus the blade's current length.
	for (int32 i = 0; i < Points.Num(); ++i)
	{
		Hits.Reset();
		GetWorld()->SweepMultiByObjectType(Hits, PrevBladePoints[i], Points[i], FQuat::Identity, ObjectParams, Shape, Params);
		Consider(Hits);
	}
	Hits.Reset();
	GetWorld()->SweepMultiByObjectType(Hits, Points[0], Points.Last(), FQuat::Identity, ObjectParams, Shape, Params);
	Consider(Hits);

	PrevBladePoints = Points;
}

void ABFPlayerCharacter::ApplyWeaponHit(ABFEnemyBase* Target, const FVector& ImpactPoint)
{
	const TArray<FBFAttackDef>& Defs = GetChainDefs(CurrentChain);
	const FBFAttackDef& Def = Defs[ComboIndex];
	// Only the last window of a finisher knocks down; earlier swings of it hit normally.
	const bool bFinisherHit = Def.bFinisher && ActiveWindow == Def.Windows.Num() - 1;

	if (bExecuting)
	{
		bExecuting = false;
		if (Target->IsBroken())
		{
			Target->ReceiveExecution(this);
			const FBFImpactProfile& Exec = BFCombat::GetImpactProfile(EBFHitWeight::Execution);
			const FVector Swing = (ImpactPoint - GetActorLocation()).GetSafeNormal2D();
			ApplyHitstop(Exec.AttackerStop);
			Target->ApplyHitstop(Exec.VictimStop);
			AddCameraShake(Exec.Shake, Exec.ShakeTime, Swing, Exec.FovPunch);
			SpawnVfx(HitVfx, ImpactPoint, Swing.Rotation(), Exec.VfxScale);
			ABFRingFX::Spawn(GetWorld(), ImpactPoint, FLinearColor(0.3f, 0.75f, 1.f), 40.f, 420.f, 0.35f);
			if (HitSound)
			{
				UGameplayStatics::PlaySoundAtLocation(this, HitSound, ImpactPoint, 1.4f, 0.8f);
			}
			ImpactFrame();
			WorldSlowMo(0.3f, 0.2f);
			UE_LOG(LogTemp, Display, TEXT("BFTEST execution landed target_hp=%.0f"), Target->GetHealth());
			if (!AutoTestMode.IsEmpty())
			{
				AutoTestShot(TEXT("p_exec"));
				PendingShotName = TEXT("p_exec_post");
				PendingShotTime = AutoTestTime + 0.15f;
			}
			return;
		}
	}

	FBFHitInfo Hit;
	Hit.Damage = Def.Damage;
	Hit.PostureDamage = Def.PostureDamage;
	Hit.bFinisher = bFinisherHit;
	Hit.Weight = bFinisherHit ? EBFHitWeight::Finisher : (CurrentChain == EBFChain::Heavy ? EBFHitWeight::Heavy : EBFHitWeight::Light);
	Hit.bHeavy = CurrentChain == EBFChain::Heavy;
	Hit.ImpactPoint = ImpactPoint;
	Hit.Instigator = this;
	{
		// Blade travel at contact (tip this frame minus tip last frame) picks the react side.
		TArray<FVector> Tips;
		GetBladePoints(Tips);
		if (Tips.Num() > 0 && PrevBladePoints.Num() == Tips.Num())
		{
			Hit.SwingDir = Tips.Last() - PrevBladePoints.Last();
		}
	}
	if (!Target->ReceiveHit(Hit))
	{
		return;
	}

	// Impact profile by weight: the victim freezes longer than the attacker, and the camera
	// kicks along the swing instead of jittering randomly.
	const FBFImpactProfile& Profile = BFCombat::GetImpactProfile(Hit.Weight);
	const FVector Swing = (ImpactPoint - GetActorLocation()).GetSafeNormal2D();
	ApplyHitstop(Profile.AttackerStop);
	Target->ApplyHitstop(Profile.VictimStop);
	AddCameraShake(Profile.Shake, Profile.ShakeTime, Swing, Profile.FovPunch);

	const FRotator FacingRot = Swing.Rotation();
	const bool bArmored = Target->WasLastHitArmored();
	// Finisher uses the same blue impact as the other hits, just bigger.
	SpawnVfx(HitVfx, ImpactPoint, FacingRot, Profile.VfxScale * (bArmored ? 0.8f : 1.f));
	if (bArmored)
	{
		// Blade bites into armor: orange sparks and a metallic ring on top of the cut.
		SpawnVfx(BlockVfx, ImpactPoint, FacingRot, 0.55f * Profile.VfxScale, ParryHue);
		if (BlockSound)
		{
			UGameplayStatics::PlaySoundAtLocation(this, BlockSound, ImpactPoint, 0.45f, FMath::FRandRange(1.15f, 1.3f));
		}
	}
	if (HitSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, HitSound, ImpactPoint, 0.9f + 0.15f * static_cast<float>(Hit.Weight),
			FMath::FRandRange(0.92f, 1.08f) - 0.06f * static_cast<float>(Hit.Weight));
	}

	if (Target->WasLastHitPunish())
	{
		// Opening punished: gold burst on top of the cut.
		ABFRingFX::Spawn(GetWorld(), ImpactPoint, FLinearColor(1.f, 0.8f, 0.3f), 20.f, 180.f, 0.3f);
	}
	if (bFinisherHit)
	{
		ImpactFrame();
		WorldSlowMo(0.4f, 0.12f);
	}
	// Guard Regain (Lies of P): hitting back wins back the health lost while blocking.
	if (RegainPool > 0.f)
	{
		const float Gain = FMath::Min(RegainPool, Def.Damage * 0.9f + 2.f);
		RegainPool -= Gain;
		Health = FMath::Min(MaxHealth, Health + Gain);
		if (HitFlash)
		{
			HitFlash->Flash(FLinearColor(0.75f, 1.f, 0.8f), 0.15f, 0.35f);
		}
		UE_LOG(LogTemp, Display, TEXT("BFTEST regain +%.1f hp=%.0f pool=%.1f"), Gain, Health, RegainPool);
	}

	UE_LOG(LogTemp, Display, TEXT("BFTEST hit chain=%s idx=%d win=%d dmg=%.0f weight=%d armored=%d target_hp=%.0f"),
		CurrentChain == EBFChain::Light ? TEXT("L") : (CurrentChain == EBFChain::Air ? TEXT("A") : TEXT("H")), ComboIndex, ActiveWindow, Def.Damage, int32(Hit.Weight), bArmored ? 1 : 0, Target->GetHealth());
	if (!AutoTestMode.IsEmpty())
	{
		const FString Name = FString::Printf(TEXT("hit_%s%d_%d"), CurrentChain == EBFChain::Light ? TEXT("L") : (CurrentChain == EBFChain::Air ? TEXT("A") : TEXT("H")), ComboIndex, ActiveWindow);
		AutoTestShot(Name);
		// Second shot once the hit VFX has had time to bloom.
		PendingShotName = Name + TEXT("_post");
		PendingShotTime = AutoTestTime + 0.12f;
		// Follow the whole reaction (stagger, or knockdown and get-up).
		for (const float Dt : (bFinisherHit ? std::initializer_list<float>{ 0.35f, 0.7f, 1.2f, 1.6f, 1.9f, 2.3f, 2.7f, 3.4f } : std::initializer_list<float>{ 0.3f, 0.6f }))
		{
			PendingBurst.Add({ AutoTestTime + Dt, FString::Printf(TEXT("%s_r%03d"), *Name, FMath::RoundToInt(Dt * 100.f)) });
		}
	}
}

void ABFPlayerCharacter::TickAttack(float DeltaSeconds)
{
	UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
	if (!AnimInstance || !CurrentMontage || !AnimInstance->Montage_IsPlaying(CurrentMontage))
	{
		EndAction();
		return;
	}

	const TArray<FBFAttackDef>& Defs = GetChainDefs(CurrentChain);
	const FBFAttackDef& Def = Defs[ComboIndex];
	const float Pos = AnimInstance->Montage_GetPosition(CurrentMontage);

	if (bAirAttack && GetCharacterMovement()->MovementMode == MOVE_Flying)
	{
		// Hover at the height the combo started (root motion carries it forward). The last swing leaps
		// and cuts down: drop with it so the landing pose meets the floor.
		FVector L = GetActorLocation();
		L.Z = FMath::FInterpTo(L.Z, AirHoverZ, DeltaSeconds, 14.f);
		SetActorLocation(L, true);
		if (Def.bFinisher && Def.Windows.Num() > 0 && Pos >= Def.Windows.Last().End + 0.08f)
		{
			GetCharacterMovement()->SetMovementMode(MOVE_Falling);
			GetCharacterMovement()->Velocity.Z = -700.f;
		}
	}

	if (bAirAttack)
	{
		// Close in on the nearest foe and stop at sword reach, facing it (the clips' own lunge is ignored:
		// it flew past the target); nothing near: drift forward.
		if (const ABFEnemyBase* Target = FindSoftLockTarget(450.f))
		{
			const FVector To = (Target->GetActorLocation() - GetActorLocation()) * FVector(1.f, 1.f, 0.f);
			const float Gap = To.Size() - (Target->GetCapsuleComponent()->GetScaledCapsuleRadius() + 70.f);
			if (Gap > 0.f)
			{
				AddActorWorldOffset(To.GetSafeNormal() * FMath::Min(Gap, 900.f * DeltaSeconds), true);
			}
			SetActorRotation(FMath::RInterpTo(GetActorRotation(), FRotator(0.f, To.Rotation().Yaw, 0.f), DeltaSeconds, 14.f));
		}
		else
		{
			AddActorWorldOffset(GetActorForwardVector() * 120.f * DeltaSeconds, true);
		}
	}

	// Which swing window is open now?
	int32 Window = INDEX_NONE;
	for (int32 i = 0; i < Def.Windows.Num(); ++i)
	{
		if (Pos >= Def.Windows[i].Start && Pos <= Def.Windows[i].End)
		{
			Window = i;
			break;
		}
	}
	if (Window != ActiveWindow)
	{
		ActiveWindow = Window;
		if (Window != INDEX_NONE)
		{
			HitThisWindow.Reset();
			if (CurrentChain == EBFChain::Air)
			{
				const ABFEnemyBase* Near = FindSoftLockTarget(600.f);
				UE_LOG(LogTemp, Display, TEXT("BFTEST air window idx=%d pos=%.2f tip_z=%.0f dist=%.0f anim=%s"), ComboIndex, Pos,
					Sword->GetComponentLocation().Z - GetActorLocation().Z, Near ? FVector::Dist2D(Near->GetActorLocation(), GetActorLocation()) : -1.f,
					CurrentMontage ? *CurrentMontage->GetName() : TEXT("none"));
			}
			if (SwingSound)
			{
				UGameplayStatics::PlaySoundAtLocation(this, SwingSound, Sword->GetComponentLocation(), 0.8f, FMath::FRandRange(0.95f, 1.1f));
			}
			SweepBlade(true);
		}
	}
	else if (ActiveWindow != INDEX_NONE)
	{
		SweepBlade(false);
	}

	const bool bFresh = Buffered != EBuffered::None && GetWorld()->GetRealTimeSeconds() - BufferedTime < BufferWindow;
	if (!bFresh)
	{
		Buffered = EBuffered::None;
	}

	if (bAirAttack)
	{
		// Air chain: light continues the hovering swings, heavy turns any of them into a plunge.
		if (bFresh && Buffered == EBuffered::Heavy && CanCancelAttack())
		{
			StartPlunge();
			return;
		}
		if (bFresh && Buffered == EBuffered::Light && Pos >= Def.CancelTime && ComboIndex + 1 < AirChain.Num()
			&& GetCharacterMovement()->MovementMode == MOVE_Flying)
		{
			StartAirAttack(ComboIndex + 1);
			return;
		}
		if (Pos > Def.CancelTime + 0.3f && HasRecentMoveInput())
		{
			AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
			EndAction();
		}
		return;
	}

	// Jump cancels the same way the dash does (recovery, or the rest of a swing once it connected).
	if (bFresh && Buffered == EBuffered::Jump && CanCancelAttack())
	{
		CancelAttackIntoJump();
		return;
	}

	// Dash cancels anything outside an open hit window, and the rest of a swing once it connected.
	if (bFresh && Buffered == EBuffered::Dash && CanCancelAttack())
	{
		if (ActiveWindow != INDEX_NONE)
		{
			UE_LOG(LogTemp, Display, TEXT("BFTEST cancel dash after connect"));
		}
		StartDash();
		return;
	}

	if (bFresh && Pos >= Def.CancelTime && (Buffered == EBuffered::Light || Buffered == EBuffered::Heavy))
	{
		const EBFChain Wanted = Buffered == EBuffered::Light ? EBFChain::Light : EBFChain::Heavy;
		const int32 NumInChain = (Wanted == EBFChain::Light ? LightChain : HeavyChain).Num();
		// Same button continues the chain; switching buttons or finishing restarts from the first swing.
		const int32 Next = (Wanted == CurrentChain && ComboIndex + 1 < NumInChain) ? ComboIndex + 1 : 0;
		StartAttack(Wanted, Next);
		return;
	}

	// Movement input cancels the long recovery tail.
	if (Pos > Def.CancelTime + 0.3f && HasRecentMoveInput())
	{
		AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
		EndAction();
	}
}

void ABFPlayerCharacter::StartDash()
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (!DashAnim || Now < DashReadyTime)
	{
		return;
	}
	if (DashCharges <= 0)
	{
		// Out of dodge charges: refused (the HUD pips flash red).
		DashEmptyTime = Now;
		UE_LOG(LogTemp, Display, TEXT("BFTEST dash refused charges=0"));
		return;
	}

	// Dash where the stick points; with no input, forward (locked on: away from the target).
	FVector Dir = HasRecentMoveInput() ? LastMoveInput : GetActorForwardVector();
	if (!HasRecentMoveInput() && bLockedOn && LockTarget.IsValid())
	{
		Dir = -(LockTarget->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
	}
	// Dashing out of a swing with an enemy close: blink through to his far side (DoBlink).
	bBlinkPending = false;
	bBlinked = false;
	BlinkTarget = nullptr;
	if (State == EBFPlayerState::Attacking && !bAirAttack && !bTutNoBlink)
	{
		ABFEnemyBase* Target = bLockedOn && LockTarget.IsValid() ? LockTarget.Get() : FindSoftLockTarget(BlinkRange);
		if (Target && !Target->IsDead() && FVector::Dist2D(Target->GetActorLocation(), GetActorLocation()) < BlinkRange)
		{
			BlinkTarget = Target;
			bBlinkPending = true;
			Dir = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
		}
	}
	// Dashing at a near enemy (outside a swing): blink to the front of him, the side we come from.
	// Not while he is attacking: then the dash is a dodge into his swing (perfect dodge / clash).
	bBlinkFront = false;
	if (!bBlinkPending && !bAirAttack && !bTutNoBlink)
	{
		ABFEnemyBase* Target = bLockedOn && LockTarget.IsValid() ? LockTarget.Get() : FindSoftLockTarget(GapCloseRange);
		if (Target && !Target->IsDead() && !Target->IsAttacking())
		{
			const FVector ToTarget = Target->GetActorLocation() - GetActorLocation();
			const float Reach = Target->GetCapsuleComponent()->GetScaledCapsuleRadius() + GetCapsuleComponent()->GetScaledCapsuleRadius() + 70.f;
			if (ToTarget.Size2D() < GapCloseRange && ToTarget.Size2D() > Reach + 60.f && FVector::DotProduct(Dir, ToTarget.GetSafeNormal2D()) > 0.7f)
			{
				BlinkTarget = Target;
				bBlinkPending = true;
				bBlinkFront = true;
				Dir = ToTarget.GetSafeNormal2D();
			}
		}
	}
	// Slide dash (Lucy clips). Free: turn to the dash direction and slide forward. Locked on: keep
	// facing the target and pick the forward / back / left / right slide closest to the direction.
	UAnimSequence* Clip = DashAnim;
	float Rate = DashPlayRate;
	float Travel = 1.f;
	int32 Slide = 0;
	FRotator Facing(0.f, Dir.Rotation().Yaw, 0.f);
	if (!(bLockedOn && LockTarget.IsValid()) && !bBlinkPending && Controller && HasRecentMoveInput())
	{
		// Free: the stick relative to the camera picks the slide (W / none forward, A left, D right,
		// S back); the body turns so that clip's travel runs exactly along the input.
		const float CamYaw = Controller->GetControlRotation().Yaw;
		const float Rel = FMath::FindDeltaAngleDegrees(CamYaw, Dir.Rotation().Yaw);
		Slide = FMath::Abs(Rel) <= 45.f ? 0 : FMath::Abs(Rel) >= 135.f ? 1 : Rel < 0.f ? 2 : 3;
		static const float SlideYawOffset[4] = { 0.f, 180.f, 90.f, -90.f };
		Facing = FRotator(0.f, Dir.Rotation().Yaw + SlideYawOffset[Slide], 0.f);
	}
	if (bLockedOn && LockTarget.IsValid())
	{
		const FVector ToTarget = (LockTarget->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
		if (!ToTarget.IsNearlyZero())
		{
			const float Rel = FMath::FindDeltaAngleDegrees(ToTarget.Rotation().Yaw, Dir.Rotation().Yaw);
			Slide = FMath::Abs(Rel) <= 45.f ? 0 : FMath::Abs(Rel) >= 135.f ? 1 : Rel < 0.f ? 2 : 3;
			Facing = FRotator(0.f, ToTarget.Rotation().Yaw, 0.f);
		}
	}
	if (SlideAnims.IsValidIndex(Slide) && SlideAnims[Slide])
	{
		Clip = SlideAnims[Slide];
		Rate = SlideRate[Slide];
		Travel = SlideTravelScale[Slide];
	}
	SetActorRotation(Facing);
	if (!PlayAnim(Clip, Rate, 0.04f, 0.2f))
	{
		return;
	}
	SetAnimRootMotionTranslationScale(Travel);
	static const TCHAR* SlideNames[] = { TEXT("F"), TEXT("B"), TEXT("L"), TEXT("R") };
	UE_LOG(LogTemp, Display, TEXT("BFTEST slide %s clip=%s"), Clip == DashAnim ? TEXT("roll") : SlideNames[Slide], *GetNameSafe(Clip));
	// Reload: starts when the stack first drops below max and always takes DashRefillDelay; rolls during
	// the reload do not restart it (user, 2026-11-10).
	const bool bWasFull = DashCharges >= BFCombat::MaxDashCharges;
	--DashCharges;
	DashPressRealTime = GetWorld()->GetRealTimeSeconds();
	if (bWasFull)
	{
		DashReloadStartTime = Now;
	}
	bDashRewarded = false;
	DashDir = Dir;
	DashStartLoc = GetActorLocation();
	DashHistory.Add(Now);
	DashHistory.RemoveAll([Now](double T) { return Now - T > 6.0; });
	UE_LOG(LogTemp, Display, TEXT("BFTEST dash charges=%d"), DashCharges);

	State = EBFPlayerState::Dashing;
	ActiveWindow = INDEX_NONE;
	Buffered = EBuffered::None;
	bInvulnerable = true;
	AfterImageTimer = 0.f;
	SpawnAfterImage();
	// Dash whoosh: the katana swing, pitched down into a body-sized rush of air.
	if (SwingSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, SwingSound, GetActorLocation(), 0.75f, FMath::FRandRange(0.62f, 0.72f));
	}
}

void ABFPlayerCharacter::TickDash(float DeltaSeconds)
{
	UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
	if (!AnimInstance || !CurrentMontage || !AnimInstance->Montage_IsPlaying(CurrentMontage))
	{
		EndAction();
		return;
	}

	const float Pos = AnimInstance->Montage_GetPosition(CurrentMontage);
	bInvulnerable = Pos < DashIFrameEnd;
	if (bBlinkPending && Pos >= BlinkAt)
	{
		DoBlink();
	}

	if (Pos < DashGhostEnd)
	{
		AfterImageTimer += DeltaSeconds;
		if (AfterImageTimer >= 0.035f)
		{
			AfterImageTimer = 0.f;
			SpawnAfterImage();
		}
	}
	if (!AutoTestMode.IsEmpty() && Pos > 0.25f)
	{
		AutoTestShot(TEXT("dash"));
	}

	const bool bFresh = Buffered != EBuffered::None && GetWorld()->GetRealTimeSeconds() - BufferedTime < BufferWindow;
	if (bFresh && Pos >= DashChainTime)
	{
		if (Buffered == EBuffered::Light || Buffered == EBuffered::Heavy)
		{
			StartAttack(Buffered == EBuffered::Light ? EBFChain::Light : EBFChain::Heavy, 0);
			return;
		}
		if (Buffered == EBuffered::Dash && Pos >= DashChainTime + 0.1f)
		{
			State = EBFPlayerState::Free;
			StartDash();
			return;
		}
	}

	if (Pos > 0.65f && HasRecentMoveInput())
	{
		AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
		EndAction();
	}
}

void ABFPlayerCharacter::DoBlink()
{
	bBlinkPending = false;
	ABFEnemyBase* Target = BlinkTarget.Get();
	if (!Target || Target->IsDead())
	{
		return;
	}
	const FVector From = GetActorLocation();
	FVector Through = (Target->GetActorLocation() - From).GetSafeNormal2D();
	if (Through.IsNearlyZero())
	{
		Through = GetActorForwardVector();
	}
	const float Gap = Target->GetCapsuleComponent()->GetScaledCapsuleRadius() + GetCapsuleComponent()->GetScaledCapsuleRadius() + 70.f;
	FVector Dest = Target->GetActorLocation() + (bBlinkFront ? -Through : Through) * Gap;
	Dest.Z = From.Z;
	// Needs floor on the far side (arena edge, pit) and a spot the capsule fits; otherwise a plain dash.
	FHitResult Floor;
	FCollisionQueryParams Params(SCENE_QUERY_STAT(BFBlink), false, this);
	Params.AddIgnoredActor(Target);
	const float Half = GetCapsuleComponent()->GetScaledCapsuleHalfHeight();
	if (!GetWorld()->LineTraceSingleByChannel(Floor, Dest + FVector(0.f, 0.f, 100.f), Dest - FVector(0.f, 0.f, Half + 250.f), ECC_WorldStatic, Params))
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST blink skipped no floor"));
		return;
	}
	Dest.Z = Floor.ImpactPoint.Z + Half + 2.f;
	const FRotator Face(0.f, (bBlinkFront ? Through : -Through).Rotation().Yaw, 0.f);
	if (!GetWorld()->FindTeleportSpot(this, Dest, Face))
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST blink skipped blocked"));
		return;
	}
	SpawnAfterImage();
	ABFRingFX::Spawn(GetWorld(), From, FLinearColor(0.35f, 0.8f, 1.f), 30.f, 220.f, 0.3f);
	SetActorLocationAndRotation(Dest, Face, false, nullptr, ETeleportType::TeleportPhysics);
	GetCharacterMovement()->Velocity = FVector::ZeroVector;
	ABFRingFX::Spawn(GetWorld(), Dest, FLinearColor(0.35f, 0.8f, 1.f), 220.f, 30.f, 0.25f);
	// Now facing him: behind, the rest of the slide eases back a little; in front, it stops dead.
	SetAnimRootMotionTranslationScale(bBlinkFront ? 0.f : -0.25f);
	if (SwordSmear)
	{
		SwordSmear->Cut();
	}
	for (UBFSmearTrail* Streak : SpeedStreaks)
	{
		Streak->Cut();
	}
	bBlinked = true;
	AfterImageTimer = 0.f;
	UE_LOG(LogTemp, Display, TEXT("BFTEST blink %s from=%s to=%s behind=%.0f"), bBlinkFront ? TEXT("front") : TEXT("back"), *From.ToCompactString(), *Dest.ToCompactString(),
		FVector::DotProduct((Dest - Target->GetActorLocation()).GetSafeNormal2D(), Target->GetActorForwardVector()));
}

void ABFPlayerCharacter::PostInitializeComponents()
{
	Super::PostInitializeComponents();
	// -BFMannequin: keep the stock UE mannequin as the visible body (footage of the bare system).
	if (FParse::Param(FCommandLine::Get(), TEXT("BFMannequin")))
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST anime body off (-BFMannequin)"));
		return;
	}
	USkeletalMesh* BodyAsset = LoadObject<USkeletalMesh>(nullptr, BFPaths::AnimeMesh);
	UClass* Anim = LoadClass<UAnimInstance>(nullptr, BFPaths::AnimeAnimBP);
	UStaticMesh* Blade = LoadObject<UStaticMesh>(nullptr, BFPaths::AnimeSword);
	if (!AnimeBody || !BodyAsset || !Anim || !Blade)
	{
		UE_LOG(LogTemp, Warning, TEXT("BFTEST anime body missing assets: mesh=%d anim=%d sword=%d"), BodyAsset != nullptr, Anim != nullptr, Blade != nullptr);
		return;
	}
	AnimeBody->SetSkeletalMesh(BodyAsset);
	AnimeBody->SetAnimationMode(EAnimationMode::AnimationBlueprint);
	AnimeBody->SetAnimInstanceClass(Anim);
	// The mannequin is hidden but must keep animating: it drives root motion, notifies and her pose.
	GetMesh()->SetVisibility(false, false);
	GetMesh()->VisibilityBasedAnimTickOption = EVisibilityBasedAnimTickOption::AlwaysTickPoseAndRefreshBones;
	// Her own sword in her right hand; offset solved from the pack's hand_r grip (19_bf_combo_setup.py).
	Sword->AttachToComponent(AnimeBody, FAttachmentTransformRules::SnapToTargetNotIncludingScale, TEXT("J_Bip_R_Hand"));
	Sword->SetRelativeLocationAndRotation(FVector(0.837f, 1.115f, -7.406f), FRotator(12.443f, 163.740f, -84.449f));
	Sword->SetStaticMesh(Blade);
}

USkeletalMeshComponent* ABFPlayerCharacter::GetVisibleBody() const
{
	return AnimeBody && AnimeBody->GetSkeletalMeshAsset() ? AnimeBody.Get() : GetMesh();
}

void ABFPlayerCharacter::SpawnAfterImage()
{
	FActorSpawnParameters Params;
	Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
	ABFAfterImage* Ghost = GetWorld()->SpawnActor<ABFAfterImage>(ABFAfterImage::StaticClass(), GetVisibleBody()->GetComponentTransform(), Params);
	if (Ghost)
	{
		Ghost->Init(GetVisibleBody(), Sword, AfterImageMaterial, FLinearColor(0.25f, 0.75f, 1.f), 0.35f);
	}
}

void ABFPlayerCharacter::EndAction()
{
	const EBFPlayerState Was = State;
	if (bAirAttack)
	{
		// Air combo over: fall back down; a buffered heavy still plunges, nothing else fires in the air.
		bAirAttack = false;
		if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
		{
			AnimInstance->SetRootMotionMode(ERootMotionMode::RootMotionFromMontagesOnly);
		}
		if (GetCharacterMovement()->MovementMode == MOVE_Flying)
		{
			GetCharacterMovement()->SetMovementMode(MOVE_Falling);
		}
		const bool bHeavyQueued = Buffered == EBuffered::Heavy && GetWorld()->GetRealTimeSeconds() - BufferedTime < BufferWindow;
		Buffered = EBuffered::None;
		State = EBFPlayerState::Free;
		ActiveWindow = INDEX_NONE;
		bInvulnerable = false;
		if (bHeavyQueued && GetCharacterMovement()->IsFalling())
		{
			StartPlunge();
		}
		return;
	}
	State = EBFPlayerState::Free;
	ActiveWindow = INDEX_NONE;
	bInvulnerable = false;
	bExecuting = false;
	if (Was == EBFPlayerState::Dashing)
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST dash end travel=%.0f"), FVector::Dist2D(DashStartLoc, GetActorLocation()));
		DashReadyTime = GetWorld()->GetRealTimeSeconds() + 0.1;
	}

	// A press that landed during the tail still fires once the action ends.
	const bool bFresh = Buffered != EBuffered::None && GetWorld()->GetRealTimeSeconds() - BufferedTime < BufferWindow;
	const EBuffered Pending = bFresh ? Buffered : EBuffered::None;
	Buffered = EBuffered::None;
	switch (Pending)
	{
	case EBuffered::Light: StartAttack(EBFChain::Light, 0); break;
	case EBuffered::Heavy: StartAttack(EBFChain::Heavy, 0); break;
	case EBuffered::Dash: StartDash(); break;
	case EBuffered::Jump: Jump(); break;
	default: break;
	}
}

void ABFPlayerCharacter::ApplyHitstop(float Duration, float Dilation)
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (HitstopEndTime <= Now)
	{
		HitstopStartTime = Now;
		HitstopMinDilation = Dilation;
	}
	HitstopMinDilation = FMath::Min(HitstopMinDilation, Dilation);
	HitstopEndTime = FMath::Max(HitstopEndTime, Now + Duration);
	CustomTimeDilation = HitstopMinDilation;
}

void ABFPlayerCharacter::AddCameraShake(float Amplitude, float Duration, const FVector& WorldDir, float FovPunch)
{
	if (Amplitude >= ShakeAmplitude * (1.f - ShakeTime / FMath::Max(ShakeDuration, 0.01f)))
	{
		ShakeAmplitude = Amplitude;
		ShakeDuration = Duration;
		ShakeTime = 0.f;
		// The camera's relative rotation is identity outside the clash cam, so its world rotation
		// is the boom socket's: unrotate the kick into the space SetRelativeLocation uses.
		ShakeDirLocal = WorldDir.IsNearlyZero() ? FVector::ZeroVector : FollowCamera->GetComponentRotation().UnrotateVector(WorldDir.GetSafeNormal());
		ShakeRoll = ShakeDirLocal.IsNearlyZero() ? 0.f : FMath::Sign(ShakeDirLocal.Y + 0.001f) * Amplitude * 0.3f;
		ShakeFovPunch = FovPunch;
	}
}

float ABFPlayerCharacter::GetHurtFlash() const
{
	const float T = static_cast<float>(GetWorld()->GetRealTimeSeconds() - HurtTime);
	return T < 0.f || T > 0.6f ? 0.f : FMath::Square(1.f - T / 0.6f);
}

// ---------------------------------------------------------------------------------------------
// Defense: guard, parry, posture, hit reactions, execution


void ABFPlayerCharacter::OnGuardPressed()
{
	bGuardHeld = true;
	if (State == EBFPlayerState::Clashing)
	{
		StrugglePress();
		return;
	}
	if (GetCharacterMovement()->IsFalling() || bCinematic || bGrabbed)
	{
		return;
	}
	// Guard can cut into anything except an open hit window that has not connected yet, an
	// execution or the dash i-frames.
	const bool bCanGuard = State == EBFPlayerState::Free || State == EBFPlayerState::Guarding
		|| (State == EBFPlayerState::Attacking && CanCancelAttack() && !bExecuting)
		|| (State == EBFPlayerState::Dashing && !bInvulnerable);
	if (bCanGuard)
	{
		if (State == EBFPlayerState::Attacking && ActiveWindow != INDEX_NONE)
		{
			UE_LOG(LogTemp, Display, TEXT("BFTEST cancel guard after connect"));
		}
		StartGuard();
	}
	else
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST guard refused state=%d"), int32(State));
	}
}

void ABFPlayerCharacter::OnGuardReleased()
{
	bGuardHeld = false;
}

void ABFPlayerCharacter::StartGuard()
{
	// Every fresh press opens a new perfect-parry window.
	ParryPressTime = GetWorld()->GetRealTimeSeconds();
	FaceForAction();
	if (State != EBFPlayerState::Guarding)
	{
		PlayAnim(GuardAnim, 1.4f, 0.05f, 0.2f);
		State = EBFPlayerState::Guarding;
		ActiveWindow = INDEX_NONE;
		bInvulnerable = false;
		Buffered = EBuffered::None;
	}
}

void ABFPlayerCharacter::TickGuard(float DeltaSeconds)
{
	UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
	const bool bPlaying = AnimInstance && CurrentMontage && AnimInstance->Montage_IsPlaying(CurrentMontage);
	const double Now = GetWorld()->GetRealTimeSeconds();

	// Hold the crouched block pose of the depence clip.
	if (bPlaying && AnimInstance->Montage_GetPosition(CurrentMontage) >= 0.22f)
	{
		AnimInstance->Montage_SetPlayRate(CurrentMontage, 0.f);
	}

	// A tap still covers the (heavy) parry window; after that, guard lasts while the button is held.
	if (!bGuardHeld && Now - ParryPressTime > BFCombat::HeavyParryWindow + 0.05)
	{
		if (bPlaying)
		{
			AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
		}
		EndAction();
		return;
	}
	if (!bPlaying)
	{
		PlayAnim(GuardAnim, 1.4f, 0.05f, 0.2f);
	}
	TurnTowardSoftLock(DeltaSeconds);
}

void ABFPlayerCharacter::TurnTowardSoftLock(float DeltaSeconds)
{
	if (const ABFEnemyBase* Target = GetFacingTarget(700.f))
	{
		const FVector To = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
		if (!To.IsNearlyZero())
		{
			SetActorRotation(FMath::RInterpConstantTo(GetActorRotation(), FRotator(0.f, To.Rotation().Yaw, 0.f), DeltaSeconds, 540.f));
		}
	}
}

void ABFPlayerCharacter::AddPosture(float Amount)
{
	Posture = FMath::Min(MaxPosture, Posture + Amount);
	LastPostureDamageTime = GetWorld()->GetRealTimeSeconds();
}

void ABFPlayerCharacter::StartStun(float Duration, UAnimSequence* Anim, float Rate)
{
	SetAnimRootMotionTranslationScale(1.f); // callers set their own push after
	PlayAnim(Anim, Rate, 0.03f, 0.2f);
	State = EBFPlayerState::Stunned;
	StunEndTime = GetWorld()->GetRealTimeSeconds() + Duration;
	ActiveWindow = INDEX_NONE;
	bInvulnerable = false;
	bKnockedDown = false;
	bGettingUp = false;
	DownLoopAt = 0.0;
	bExecuting = false;
	Buffered = EBuffered::None;
}

void ABFPlayerCharacter::SpawnVfx(UNiagaraSystem* System, const FVector& Location, const FRotator& Rotation, float SizeScale, float Hue)
{
	if (!System)
	{
		return;
	}
	UNiagaraComponent* Comp = UNiagaraFunctionLibrary::SpawnSystemAtLocation(GetWorld(), System, Location, Rotation);
	if (!Comp)
	{
		return;
	}
	if (!FMath::IsNearlyEqual(SizeScale, 1.f))
	{
		// Scale the system's own size parameter (SlashHitVFX exposes User._Size).
		const FNiagaraVariable SizeVar(FNiagaraTypeDefinition::GetFloatDef(), TEXT("User._Size"));
		const float Base = Comp->GetOverrideParameters().GetParameterValue<float>(SizeVar);
		Comp->SetVariableFloat(TEXT("_Size"), (Base > 0.f ? Base : 1.f) * SizeScale);
	}
	if (Hue >= 0.f)
	{
		Comp->SetVariableFloat(TEXT("ColorHue"), Hue);
	}
}

void ABFPlayerCharacter::DoParry(ABFEnemyBase* Attacker, const FBFHitInfo& Hit)
{
	const FVector Contact = FMath::Lerp(GetActorLocation(), Attacker->GetActorLocation(), 0.4f) + FVector(0.f, 0.f, 45.f);
	const FRotator Facing = (Attacker->GetActorLocation() - GetActorLocation()).GetSafeNormal2D().Rotation();

	ApplyHitstop(BFCombat::HitstopParry);
	Attacker->ApplyHitstop(BFCombat::HitstopParry);
	AddCameraShake(6.f, 0.2f);

	// Orange ring flash plus sparks, as in the reference clip.
	ABFRingFX::Spawn(GetWorld(), Contact, ParryOrange, 30.f, 260.f, 0.28f);
	ABFRingFX::Spawn(GetWorld(), Contact, FLinearColor(1.f, 0.55f, 0.2f), 10.f, 120.f, 0.16f);
	SpawnVfx(BlockVfx, Contact, Facing, 1.3f, ParryHue);
	if (ParrySound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, ParrySound, Contact, 1.2f, FMath::FRandRange(1.0f, 1.12f));
	}
	AddPosture(4.f);

	if (Hit.bHeavy)
	{
		// Big attack: blades lock, clash cinematic, mash guard to win the strength contest.
		UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=PARRY heavy -> clash"));
		StartStruggle(Attacker, Hit, Contact);
		return;
	}

	// Normal attack: plain deflect, gameplay camera stays.
	Attacker->OnParried(this);
	UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=PARRY player_posture=%.0f enemy_posture=%.0f"), Posture, Attacker->GetPosture());
}

// ---------------------------------------------------------------------------------------------
// Strength clash: after parrying a heavy attack both fighters lock blades. Each guard press
// pushes the bar toward the player; the enemy pushes back continuously. Fill the bar, or be
// ahead when time runs out, to win.

namespace BFStruggle
{
	constexpr float Duration = 2.5f;     // real seconds
	constexpr float PressGain = 0.1f;    // bar per press
	constexpr float WorldSlowMo = 0.3f;  // sparks keep crawling while locked
}

float ABFPlayerCharacter::GetStruggleTimeLeft01() const
{
	if (!bStruggle)
	{
		return 0.f;
	}
	const float Elapsed = float(GetWorld()->GetRealTimeSeconds() - StruggleStart);
	return FMath::Clamp(1.f - Elapsed / BFStruggle::Duration, 0.f, 1.f);
}

void ABFPlayerCharacter::EndHitstop()
{
	HitstopEndTime = 0.0;
	CustomTimeDilation = 1.f;
}

void ABFPlayerCharacter::StartStruggle(ABFEnemyBase* Attacker, const FBFHitInfo& Hit, const FVector& Contact)
{
	bStruggle = true;
	StruggleStart = GetWorld()->GetRealTimeSeconds();
	StruggleBalance = 0.f;
	StrugglePunch = 0.f;
	StruggleEnemyPush = Attacker->GetClashPush();
	StruggleContact = Contact;
	StruggleEnemy = Attacker;
	StruggleHit = Hit;
	++StruggleCount;
	State = EBFPlayerState::Clashing;
	Buffered = EBuffered::None;
	StartClashCam(Attacker, Contact, true);
	UE_LOG(LogTemp, Display, TEXT("BFTEST struggle start #%d enemy=%s push=%.2f"), StruggleCount, Attacker->IsBoss() ? TEXT("boss") : TEXT("minion"), StruggleEnemyPush);
}

void ABFPlayerCharacter::StrugglePress()
{
	if (!bStruggle)
	{
		return;
	}
	StruggleBalance += BFStruggle::PressGain;
	StrugglePunch = 1.f;
	// Quick ring pop on each push (real-time, fades fast); sparks only every third press so
	// slow-motion Niagara bursts do not pile up over the blades.
	const FVector Jitter = FMath::VRand() * 8.f;
	ABFRingFX::Spawn(GetWorld(), StruggleContact + Jitter, FLinearColor(1.f, 0.5f, 0.1f), 8.f, 70.f, 0.12f);
	if (++StrugglePressCount % 3 == 0)
	{
		SpawnVfx(BlockVfx, StruggleContact + Jitter, FRotator(FMath::FRandRange(-30.f, 30.f), FMath::FRandRange(0.f, 360.f), 0.f), 0.15f, ParryHue);
	}
	if (BlockSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, BlockSound, StruggleContact, 0.35f, FMath::FRandRange(1.1f, 1.35f));
	}
}

void ABFPlayerCharacter::TickStruggle(float RealDelta)
{
	if (!StruggleEnemy.IsValid())
	{
		ResolveStruggle(false);
		return;
	}
	StruggleBalance -= StruggleEnemyPush * RealDelta;
	StrugglePunch = FMath::Max(0.f, StrugglePunch - RealDelta * 6.f);
	const float Elapsed = float(GetWorld()->GetRealTimeSeconds() - StruggleStart);
	if (StruggleBalance >= 1.f)
	{
		ResolveStruggle(true);
	}
	else if (StruggleBalance <= -1.f)
	{
		ResolveStruggle(false);
	}
	else if (Elapsed >= BFStruggle::Duration)
	{
		ResolveStruggle(StruggleBalance > 0.f);
	}
}

void ABFPlayerCharacter::ResolveStruggle(bool bWon)
{
	bStruggle = false;
	ABFEnemyBase* Enemy = StruggleEnemy.Get();
	StruggleEnemy.Reset();
	EndHitstop();
	if (Enemy)
	{
		Enemy->EndHitstop();
	}

	// Close-up holds a short beat on the outcome, then whips back.
	const double Now = GetWorld()->GetRealTimeSeconds();
	ClashHoldDuration = float(Now - ClashStartTime) - 0.1f + 0.35f;
	UGameplayStatics::SetGlobalTimeDilation(this, 0.5f);

	const FVector ToEnemy = Enemy ? (Enemy->GetActorLocation() - GetActorLocation()).GetSafeNormal2D() : GetActorForwardVector();
	Buffered = EBuffered::None; // presses during the contest were mashing, not orders
	if (bWon)
	{
		EndAction();
		ABFRingFX::Spawn(GetWorld(), StruggleContact, ParryOrange, 40.f, 340.f, 0.35f);
		SpawnVfx(HitVfx, StruggleContact, ToEnemy.Rotation(), 1.6f);
		if (HitSound)
		{
			UGameplayStatics::PlaySoundAtLocation(this, HitSound, StruggleContact, 1.3f, 0.85f);
		}
		ApplyHitstop(0.1f);
		if (Enemy)
		{
			Enemy->OnClashLost(this);
			Enemy->ApplyHitstop(0.1f);
		}
		UE_LOG(LogTemp, Display, TEXT("BFTEST struggle WIN balance=%.2f"), StruggleBalance);
	}
	else
	{
		Health = FMath::Max(0.f, Health - StruggleHit.Damage * 0.6f);
		AddPosture(40.f);
		ABFRingFX::Spawn(GetWorld(), StruggleContact, FLinearColor(1.f, 0.03f, 0.02f), 30.f, 280.f, 0.3f);
		SpawnVfx(HitVfx, GetActorLocation() + FVector(0.f, 0.f, 40.f), (-ToEnemy).Rotation(), 1.4f);
		if (HitSound)
		{
			UGameplayStatics::PlaySoundAtLocation(this, HitSound, GetActorLocation());
		}
		// Overpowered: knocked up and back off the locked blades, lands on the back, then gets up
		// (the clip's root motion carries the body ~2 m; a small hop adds air).
		SetActorRotation(FRotator(0.f, ToEnemy.Rotation().Yaw, 0.f));
		StartKnockdown(BlowbackAnim ? BlowbackAnim.Get() : KnockdownAnim.Get(), 0.5f);
		LaunchCharacter(FVector(0.f, 0.f, 420.f), false, true);
		if (HitFlash)
		{
			HitFlash->Flash(FLinearColor(0.9f, 0.01f, 0.f), 0.3f, 0.85f);
		}
		HurtTime = Now;
		if (Enemy)
		{
			Enemy->OnClashWon(this);
		}
		if (Health <= 0.f)
		{
			UE_LOG(LogTemp, Display, TEXT("BFTEST player down (refilled until phase 8)"));
			Health = MaxHealth;
		}
		UE_LOG(LogTemp, Display, TEXT("BFTEST struggle LOSE balance=%.2f player_hp=%.0f"), StruggleBalance, Health);
	}
	AddCameraShake(12.f, 0.35f);
	StrugglePunch = 0.f;
	if (!AutoTestMode.IsEmpty())
	{
		AutoTestShot(FString::Printf(TEXT("struggle%d_%s"), StruggleCount, bWon ? TEXT("win") : TEXT("lose")));
		PendingBurst.Add({ AutoTestTime + 0.3f, FString::Printf(TEXT("struggle%d_after"), StruggleCount) });
		PendingBurst.Add({ AutoTestTime + 1.0f, FString::Printf(TEXT("struggle%d_back"), StruggleCount) });
		if (!bWon)
		{
			for (const float Dt : { 0.6f, 1.3f, 1.6f, 1.9f, 2.1f, 2.4f, 2.8f })
			{
				PendingBurst.Add({ AutoTestTime + Dt, FString::Printf(TEXT("struggle%d_kb%03d"), StruggleCount, FMath::RoundToInt(Dt * 100.f)) });
			}
		}
	}
}

// ---------------------------------------------------------------------------------------------
// Clash cinematic. Timings measured from the reference clip (30 fps):
// ~0.1 s whip-in with motion blur, near-frozen close-up, ~0.13 s whip back to gameplay.

namespace BFClash
{
	constexpr float In = 0.10f;
	constexpr float Hold = 0.50f;
	constexpr float Out = 0.14f;
	constexpr float FlashSlowMo = 0.35f; // whip-in: the parry flash still plays out
	constexpr float SlowMo = 0.04f;      // hold: sparks crawl
	constexpr float Fov = 72.f;
}

void ABFPlayerCharacter::StartClashCam(ABFEnemyBase* Attacker, const FVector& Contact, bool bStruggleHold)
{
	const FVector Fwd = (Attacker->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
	const FVector Right = FVector::CrossProduct(FVector::UpVector, Fwd);

	// Low, close, behind the player's left shoulder: the player fills the right of frame,
	// the enemy and the crossed blades sit left of centre (as in the reference shot).
	ClashCamLoc = GetActorLocation() - Fwd * 150.f - Right * 70.f + FVector(0.f, 0.f, 42.f);
	const FVector LookAt = Contact + Fwd * 15.f - FVector(0.f, 0.f, 18.f);
	ClashCamRot = (LookAt - ClashCamLoc).Rotation();
	ClashCamRot.Roll = 6.f; // slight dutch tilt
	ClashPushDir = (LookAt - ClashCamLoc).GetSafeNormal();

	bClashCam = true;
	bClashStruggleMode = bStruggleHold;
	ClashStartTime = GetWorld()->GetRealTimeSeconds();
	// A strength clash holds until it resolves (ResolveStruggle shortens this).
	ClashHoldDuration = bStruggleHold ? 1000.f : BFClash::Hold;

	// Freeze both fighters through the beat; the world (sparks, debris) crawls in slow motion.
	const float Total = BFClash::In + ClashHoldDuration;
	ApplyHitstop(Total, BFCombat::HitstopDilation);
	Attacker->ApplyHitstop(Total, BFCombat::HitstopDilation);
	UGameplayStatics::SetGlobalTimeDilation(this, BFClash::FlashSlowMo);
	ShakeAmplitude = 0.f;
	ShakeTime = ShakeDuration;
	UE_LOG(LogTemp, Display, TEXT("BFTEST clashcam start"));

	if (!AutoTestMode.IsEmpty())
	{
		for (const float At : { 0.12f, 0.6f, 1.4f })
		{
			PendingBurst.Add({ AutoTestTime + At, FString::Printf(TEXT("clash%d_%03d"), StruggleCount, FMath::RoundToInt(At * 100.f)) });
		}
	}
}

void ABFPlayerCharacter::TickClashCam()
{
	const float T = float(GetWorld()->GetRealTimeSeconds() - ClashStartTime);
	const float HoldEnd = BFClash::In + ClashHoldDuration;
	if (T >= HoldEnd + BFClash::Out)
	{
		EndClashCam();
		return;
	}

	float Alpha = 1.f;
	if (T < BFClash::In)
	{
		Alpha = 1.f - FMath::Pow(1.f - T / BFClash::In, 3.f); // fast start, soft landing
	}
	else if (T <= HoldEnd)
	{
		const float Want = bStruggle ? BFStruggle::WorldSlowMo : (bClashStruggleMode ? 0.5f : BFClash::SlowMo);
		if (!FMath::IsNearlyEqual(UGameplayStatics::GetGlobalTimeDilation(this), Want))
		{
			UGameplayStatics::SetGlobalTimeDilation(this, Want);
		}
	}
	else
	{
		const float X = (T - HoldEnd) / BFClash::Out;
		Alpha = 1.f - X * X; // ease-in whip back
		if (UGameplayStatics::GetGlobalTimeDilation(this) < 1.f)
		{
			UGameplayStatics::SetGlobalTimeDilation(this, 1.f);
		}
	}
	Alpha = FMath::Clamp(Alpha, 0.f, 1.f);
	// Push-in over the beat: 0.5 s for a plain clash, the whole contest for a strength clash.
	const float PushSpan = bClashStruggleMode ? BFStruggle::Duration : BFClash::Hold;
	const float HoldT = FMath::Clamp((T - BFClash::In) / PushSpan, 0.f, 1.f);

	// Gameplay pose the camera would have this frame.
	const FTransform Socket = CameraBoom->GetSocketTransform(USpringArmComponent::SocketName);
	const FVector GameLoc = Socket.TransformPosition(CameraBaseOffset);
	const FQuat GameRot = Socket.GetRotation();

	// Clash pose with a slow push-in and drift of the tilt during the hold.
	FVector ClashLoc = ClashCamLoc + ClashPushDir * (bClashStruggleMode ? 45.f : 20.f) * HoldT;
	FRotator ClashRot = ClashCamRot;
	ClashRot.Roll += 2.f * HoldT;
	if (bStruggle)
	{
		// Straining blades: constant tremor, a kick on each press.
		const float Amp = 1.2f + StrugglePunch * 5.f;
		ClashLoc += FMath::VRand() * Amp;
		ClashRot.Roll += FMath::FRandRange(-1.f, 1.f) * (0.4f + StrugglePunch * 1.5f);
		ClashRot.Pitch += FMath::FRandRange(-1.f, 1.f) * 0.1f * Amp;
	}

	FollowCamera->SetWorldLocationAndRotation(FMath::Lerp(GameLoc, ClashLoc, Alpha), FQuat::Slerp(GameRot, ClashRot.Quaternion(), Alpha));
	FollowCamera->SetFieldOfView(FMath::Lerp(CameraBaseFov, BFClash::Fov - (bStruggle ? StrugglePunch * 2.f : 0.f), Alpha));
	FollowCamera->PostProcessBlendWeight = Alpha;
}

void ABFPlayerCharacter::EndClashCam()
{
	bClashCam = false;
	bClashStruggleMode = false;
	UGameplayStatics::SetGlobalTimeDilation(this, 1.f);
	FollowCamera->SetRelativeLocationAndRotation(CameraBaseOffset, FRotator::ZeroRotator);
	FollowCamera->SetFieldOfView(CameraBaseFov);
	FollowCamera->PostProcessBlendWeight = 0.f;
	UE_LOG(LogTemp, Display, TEXT("BFTEST clashcam end"));
}

void ABFPlayerCharacter::PerfectDodgeFeedback(ABFEnemyBase* Attacker)
{
	// Screen shake marks the perfect dodge; a cool flash and a brief world slow-down sell it.
	AddCameraShake(9.f, 0.3f);
	const FVector At = GetActorLocation() + FVector(0.f, 0.f, 30.f);
	ABFRingFX::Spawn(GetWorld(), At, FLinearColor(0.35f, 0.75f, 1.f), 20.f, 220.f, 0.3f);
	ABFRingFX::Spawn(GetWorld(), At, FLinearColor(0.9f, 0.95f, 1.f), 10.f, 110.f, 0.18f);
	if (Attacker)
	{
		Attacker->ApplyHitstop(0.12f);
	}
	WorldSlowMo(0.35f, 0.22f);
	SpawnAfterImage();
}

bool ABFPlayerCharacter::IsGrabDodging() const
{
	if (State == EBFPlayerState::Stunned || State == EBFPlayerState::Clashing || bGrabbed || bKnockedDown || bGettingUp)
	{
		return false;
	}
	return IsDashDodging() || GetWorld()->GetRealTimeSeconds() - DashPressRealTime <= BFCombat::GrabDodgeGrace;
}

EBFHitResult ABFPlayerCharacter::ResolveEnemyHit(const FBFHitInfo& Hit, ABFEnemyBase* Attacker)
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	const FVector ToAttacker = Attacker ? (Attacker->GetActorLocation() - GetActorLocation()).GetSafeNormal2D() : GetActorForwardVector();
	const bool bFacing = FVector::DotProduct(GetActorForwardVector(), ToAttacker) >= FMath::Cos(FMath::DegreesToRadians(80.f));
	auto Shot = [this](const TCHAR* Name)
	{
		if (!AutoTestMode.IsEmpty())
		{
			AutoTestShot(Name);
			PendingShotName = FString(Name) + TEXT("_post");
			PendingShotTime = AutoTestTime + 0.1f;
		}
	};

	if (bKnockedDown || bGettingUp || bGrabbed || bCinematic || State == EBFPlayerState::Stomping || (State == EBFPlayerState::Plunging && !bPlungeLanded))
	{
		// Floored, rising, held, in a cutscene or dropping on a head: no follow-up hits.
		return EBFHitResult::Dodged;
	}
	if (Hit.bMagic && bInvulnerable)
	{
		// Spells: a roll's i-frames slip through, but it is no perfect dodge (no charge back, no clash).
		UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=MAGIC_ROLLED"));
		Shot(TEXT("p_magicroll"));
		return EBFHitResult::Dodged;
	}

	// Perilous answers (Sekiro): the wave is jumped (rolling or guarding does not clear it), the thrust
	// is dodged INTO (mikiri), the grab only rolled through.
	if (Hit.Perilous == EBFPerilous::Sweep && GetCharacterMovement()->IsFalling())
	{
		PerfectJump(Attacker);
		return EBFHitResult::Countered;
	}
	if (Hit.Perilous == EBFPerilous::Thrust && bInvulnerable && Attacker && FVector::DotProduct(DashDir, ToAttacker) > 0.35f)
	{
		DoMikiri(Attacker);
		return EBFHitResult::Countered;
	}
	// A grab answered by a dash a little early (his windup can be held) still slips inside it.
	const bool bGrabDash = Hit.Perilous == EBFPerilous::Grab && Attacker && IsGrabDodging();
	if (Hit.Perilous == EBFPerilous::Grab && !bInvulnerable && !bGrabDash && Attacker)
	{
		StartGrabbed(Attacker, Hit);
		return EBFHitResult::Grabbed;
	}

	if ((bInvulnerable || bGrabDash) && Hit.Perilous != EBFPerilous::Sweep)
	{
		// Perfect dodge: the swing reached us while we were rolling through it (i-frames). It costs no
		// charge and earns one (normal swing or ultimate alike).
		RewardPerfectDodge();
		// A dodge never starts the strength clash (playtest feedback: a QTE after only rolling felt
		// wrong). The clash is reserved for blade meeting blade: parrying a heavy swing.
		PerfectDodgeFeedback(Attacker);
		UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=PERFECT_DODGE"));
		Shot(TEXT("p_dodge"));
		return EBFHitResult::Dodged;
	}

	// Guard: perilous grabs and waves go straight through it; a thrust can only be parried.
	const bool bGuardable = !Hit.bMagic && (Hit.Perilous == EBFPerilous::None || (Hit.Perilous == EBFPerilous::Thrust && Now - ParryPressTime <= BFCombat::ParryWindow));
	if (State == EBFPlayerState::Guarding && bFacing && Attacker && bGuardable)
	{
		if (Now - ParryPressTime <= (Hit.bHeavy ? BFCombat::HeavyParryWindow : BFCombat::ParryWindow))
		{
			DoParry(Attacker, Hit);
			Shot(*FString::Printf(TEXT("p_parry%d"), Attacker->GetAttackCount()));
			return EBFHitResult::Parried;
		}

		// Blocked: part of the damage gets through, but it stays recoverable (Guard Regain) for a while.
		const float Chip = Hit.Damage * 0.5f;
		Health = FMath::Max(0.f, Health - Chip);
		RegainPool = FMath::Min(MaxHealth - Health, RegainPool + Chip);
		RegainFadeStart = Now + 2.0;
		if (Health <= 0.f)
		{
			UE_LOG(LogTemp, Display, TEXT("BFTEST player down (refilled until phase 8)"));
			Health = MaxHealth;
			RegainPool = 0.f;
		}
		AddPosture(Hit.PostureDamage);
		const FVector Contact = GetActorLocation() + ToAttacker * 50.f + FVector(0.f, 0.f, 45.f);
		SpawnVfx(BlockVfx, Contact, ToAttacker.Rotation(), 0.8f);
		if (BlockSound)
		{
			UGameplayStatics::PlaySoundAtLocation(this, BlockSound, Contact);
		}
		LaunchCharacter(-ToAttacker * 250.f, true, false);
		if (Posture >= MaxPosture)
		{
			// Guard broken: long flinch, open to the next hit.
			StartStun(1.3f, HitReactAnims.IsValidIndex(0) ? HitReactAnims[0].Get() : nullptr, 0.4f);
			AddCameraShake(8.f, 0.3f);
			UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=GUARDBREAK"));
			Shot(TEXT("p_guardbreak"));
			return EBFHitResult::GuardBroken;
		}
		ApplyHitstop(0.05f);
		Attacker->ApplyHitstop(0.05f);
		AddCameraShake(3.f, 0.12f);
		UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=BLOCK player_posture=%.0f"), Posture);
		Shot(TEXT("p_block"));
		return EBFHitResult::Blocked;
	}

	// Clean hit. Heavy and perilous enemy attacks floor the player; normal ones flinch.
	const bool bFloor = Hit.bHeavy || Hit.Perilous != EBFPerilous::None;
	const EBFHitWeight Weight = bFloor ? EBFHitWeight::Heavy : EBFHitWeight::Light;
	const FBFImpactProfile& Profile = BFCombat::GetImpactProfile(Weight);
	const FVector Away = -ToAttacker;
	Health = FMath::Max(0.f, Health - Hit.Damage * BFCombat::TestDamageToPlayer);
	// Struck while standing in the river: the body jolts the water.
	BFFluxWater::Impact(GetWorld(), GetActorLocation() - FVector(0.f, 0.f, GetCapsuleComponent()->GetScaledCapsuleHalfHeight()), bFloor ? 110.f : 70.f, bFloor ? 0.9f : 0.45f);
	RegainPool = 0.f; // a clean hit loses whatever could still be regained
	AddPosture(Hit.Damage * 0.5f);
	// Red sparks, red body flash and a red screen-edge pulse: unmistakably "you got hit".
	SpawnVfx(HitVfx, Hit.ImpactPoint, Away.Rotation(), Profile.VfxScale, HurtHue);
	ABFRingFX::Spawn(GetWorld(), Hit.ImpactPoint, FLinearColor(1.f, 0.05f, 0.02f), 15.f, Hit.bHeavy ? 200.f : 120.f, 0.22f);
	if (HitFlash)
	{
		HitFlash->Flash(FLinearColor(0.9f, 0.01f, 0.f), Hit.bHeavy ? 0.3f : 0.18f, 0.85f);
	}
	if (UBFAnimInstance* Anim = Cast<UBFAnimInstance>(GetMesh()->GetAnimInstance()))
	{
		Anim->AddFlinch(Away, Profile.Flinch);
	}
	HurtTime = Now;
	if (HitSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, HitSound, Hit.ImpactPoint, Hit.bHeavy ? 1.3f : 1.f, Hit.bHeavy ? 0.8f : 0.95f);
	}
	// Getting hit freezes the player a beat longer than the enemy (asymmetric hitstop).
	ApplyHitstop(Profile.VictimStop);
	if (Attacker)
	{
		Attacker->ApplyHitstop(Profile.AttackerStop);
	}
	AddCameraShake(Hit.bHeavy ? 12.f : 7.f, Hit.bHeavy ? 0.4f : 0.25f, Away, Hit.bHeavy ? 6.f : 2.f);
	if (Hit.bKnockUp && KnockUpAnim)
	{
		// Phase-2 spell: thrown up into the air (the clip carries the flight), lands on the back.
		SetActorRotation(FRotator(0.f, ToAttacker.Rotation().Yaw, 0.f));
		StartKnockdown(KnockUpAnim, 0.7f);
		UE_LOG(LogTemp, Display, TEXT("BFTEST player knocked up"));
	}
	else if (bFloor && KnockdownAnim)
	{
		// hit_knockdown01 carries root motion (falls ~1.2 m back); a big launch fought it.
		SetActorRotation(FRotator(0.f, ToAttacker.Rotation().Yaw, 0.f));
		StartKnockdown(KnockdownAnim, 0.45f);
	}
	else
	{
		// Pushed the way the blow travels (Away, in body space): Lucy Avoid F / B / L / R, sped up and
		// with a shortened push. Falls back to the flinch clips.
		const float PushFwd = FVector::DotProduct(Away, GetActorForwardVector());
		const float PushRight = FVector::DotProduct(Away, GetActorRightVector());
		const int32 Push = FMath::Abs(PushFwd) >= FMath::Abs(PushRight) ? (PushFwd >= 0.f ? 0 : 1) : (PushRight < 0.f ? 2 : 3);
		UAnimSequence* PushClip = AvoidAnims.IsValidIndex(Push) ? AvoidAnims[Push].Get() : nullptr;
		if (PushClip)
		{
			StartStun(0.55f, PushClip, 1.6f);
			SetAnimRootMotionTranslationScale(Hit.bHeavy ? 0.6f : 0.42f);
			static const TCHAR* PushNames[] = { TEXT("F"), TEXT("B"), TEXT("L"), TEXT("R") };
			UE_LOG(LogTemp, Display, TEXT("BFTEST hit react avoid_%s"), PushNames[Push]);
			if (!AutoTestMode.IsEmpty())
			{
				PendingBurst.Add({ AutoTestTime + 0.25f, FString::Printf(TEXT("hr_%s_%.0f"), PushNames[Push], AutoTestTime) });
			}
		}
		else
		{
			LaunchCharacter(Away * 300.f, true, false);
			const float Side = FVector::DotProduct(ToAttacker, GetActorRightVector());
			const int32 React = FMath::Abs(Side) < 0.4f ? 0 : (Side > 0.f ? 2 : 1);
			StartStun(0.45f, HitReactAnims.IsValidIndex(React) ? HitReactAnims[React].Get() : nullptr, 1.f);
		}
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST defend result=HIT%s%s perilous=%d player_hp=%.0f since_guard=%.2f"), bFloor ? TEXT(" heavy knockdown") : TEXT(""),
		Hit.bMagic ? (Hit.bKnockUp ? TEXT(" magic knockup") : TEXT(" magic")) : TEXT(""), int32(Hit.Perilous), Health, float(Now - ParryPressTime));
	Shot(Hit.bKnockUp ? TEXT("p_knockup") : (bFloor ? TEXT("p_hitheavy") : TEXT("p_hit")));
	if (Health <= 0.f)
	{
		// Death and restart arrive in phase 8; refill for now so practice continues.
		UE_LOG(LogTemp, Display, TEXT("BFTEST player down (refilled until phase 8)"));
		Health = MaxHealth;
	}
	return EBFHitResult::Hit;
}

ABFEnemyBase* ABFPlayerCharacter::FindBrokenTarget(float Range) const
{
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		if (It->IsBroken() && FVector::Dist2D(It->GetActorLocation(), GetActorLocation()) <= Range)
		{
			return *It;
		}
	}
	return nullptr;
}

bool ABFPlayerCharacter::TryExecution()
{
	ABFEnemyBase* Target = FindBrokenTarget(300.f);
	if (!Target || !ExecutionAnim)
	{
		return false;
	}
	const bool bCanStart = State == EBFPlayerState::Free || State == EBFPlayerState::Guarding
		|| (State == EBFPlayerState::Attacking && ActiveWindow == INDEX_NONE && !bExecuting)
		|| (State == EBFPlayerState::Dashing && !bInvulnerable);
	if (!bCanStart)
	{
		return false;
	}

	const FVector To = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
	SetActorRotation(FRotator(0.f, To.Rotation().Yaw, 0.f));
	if (!PlayAnim(ExecutionAnim, 1.1f, 0.05f, 0.3f))
	{
		return false;
	}
	// Runs through the normal attack path (heavy finisher windows); the first contact executes.
	State = EBFPlayerState::Attacking;
	CurrentChain = EBFChain::Heavy;
	ComboIndex = HeavyChain.Num() - 1;
	ActiveWindow = INDEX_NONE;
	Buffered = EBuffered::None;
	bExecuting = true;
	UE_LOG(LogTemp, Display, TEXT("BFTEST execution start"));
	return true;
}

