bool ABFPlayerCharacter::TryPayAirCharge()
{
	if (bAirChargePaid)
	{
		return true;
	}
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (DashCharges <= 0)
	{
		DashEmptyTime = Now; // HUD pips flash red, as for a refused roll
		UE_LOG(LogTemp, Display, TEXT("BFTEST air refused charges=0"));
		return false;
	}
	// A running refill countdown keeps its time; with full charges nothing was counting, so start it
	// (otherwise the spent charge would refill on the next frame).
	const bool bWasFull = DashCharges >= BFCombat::MaxDashCharges;
	--DashCharges;
	if (bWasFull)
	{
		DashReloadStartTime = Now;
	}
	bAirChargePaid = true;
	UE_LOG(LogTemp, Display, TEXT("BFTEST air charge spent charges=%d refill_in=%.1f"), DashCharges, float(BFCombat::DashRefillDelay - (Now - DashReloadStartTime)));
	return true;
}

void ABFPlayerCharacter::StartAirAttack(int32 Index)
{
	if (Index == 0)
	{
		// Hover where the combo starts, but never higher than a good jump or lower than a small hop.
		bAirComboUsed = true;
		const float HalfHeight = GetCapsuleComponent()->GetScaledCapsuleHalfHeight();
		FHitResult Floor;
		FCollisionQueryParams Params(SCENE_QUERY_STAT(BFAirFloor), false, this);
		float StandZ = GetActorLocation().Z - 100.f;
		if (GetWorld()->LineTraceSingleByChannel(Floor, GetActorLocation(), GetActorLocation() - FVector(0.f, 0.f, 800.f), ECC_Visibility, Params))
		{
			StandZ = Floor.ImpactPoint.Z + HalfHeight;
		}
		// Low hover: the swings cut at chest height of a standing foe (higher, they pass over a man-sized one).
		// Man-sized foe (1.9 m): +40 cm; Sevarog (2.9 m): +90 cm.
		const ABFEnemyBase* Foe = FindSoftLockTarget(600.f);
		AirHoverZ = StandZ + (Foe ? FMath::Clamp(Foe->GetHalfHeight() * 2.f - 150.f, 35.f, 90.f) : 70.f);
		GetCharacterMovement()->StopMovementImmediately();
		GetCharacterMovement()->SetMovementMode(MOVE_Flying);
		if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
		{
			// The clips lunge 0.6-2.7 m each; that flew past the target. Drift is scripted below instead.
			AnimInstance->SetRootMotionMode(ERootMotionMode::IgnoreRootMotion);
		}
	}
	bAirAttack = true;
	StartAttack(EBFChain::Air, Index);
	if (State != EBFPlayerState::Attacking)
	{
		bAirAttack = false;
		GetCharacterMovement()->SetMovementMode(MOVE_Falling);
		return;
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST air attack idx=%d charges=%d hover=%.0f"), Index, DashCharges, AirHoverZ - GetActorLocation().Z);
}

void ABFPlayerCharacter::StartPlunge()
{
	// Dive onto the floor below (next to the nearest enemy when one is close), slam on landing.
	bAirAttack = false;
	State = EBFPlayerState::Plunging;
	ActiveWindow = INDEX_NONE;
	Buffered = EBuffered::None;
	bInvulnerable = true;
	bPlungeLanded = false;
	PlungeT = 0.f;
	PlungeFrom = GetActorLocation();
	GetCharacterMovement()->StopMovementImmediately();
	GetCharacterMovement()->SetMovementMode(MOVE_Flying);

	FVector Land = GetActorLocation() + GetActorForwardVector() * 120.f;
	if (const ABFEnemyBase* Target = FindSoftLockTarget(450.f))
	{
		const FVector To = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
		const float Reach = Target->GetCapsuleComponent()->GetScaledCapsuleRadius() + 70.f;
		const float Dist = FVector::Dist2D(Target->GetActorLocation(), GetActorLocation());
		Land = GetActorLocation() + To * FMath::Max(0.f, Dist - Reach);
		SetActorRotation(FRotator(0.f, To.Rotation().Yaw, 0.f));
	}
	const float HalfHeight = GetCapsuleComponent()->GetScaledCapsuleHalfHeight();
	FHitResult Floor;
	FCollisionQueryParams Params(SCENE_QUERY_STAT(BFPlungeFloor), false, this);
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		Params.AddIgnoredActor(*It);
	}
	PlungeTo = FVector(Land.X, Land.Y, PlungeFrom.Z - 200.f);
	if (GetWorld()->LineTraceSingleByChannel(Floor, FVector(Land.X, Land.Y, PlungeFrom.Z + 50.f), FVector(Land.X, Land.Y, PlungeFrom.Z - 1200.f), ECC_Visibility, Params))
	{
		PlungeTo.Z = Floor.ImpactPoint.Z + HalfHeight + 2.f;
	}
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		AnimInstance->SetRootMotionMode(ERootMotionMode::IgnoreRootMotion); // the dive is scripted
		if (UAnimMontage* Montage = PlayAnim(StompAnim, 1.4f, 0.05f, 0.3f))
		{
			AnimInstance->Montage_SetPosition(Montage, 0.5f);
		}
	}
	SpawnAfterImage();
	UE_LOG(LogTemp, Display, TEXT("BFTEST plunge start drop=%.0f charges=%d"), PlungeFrom.Z - PlungeTo.Z, DashCharges);
}

void ABFPlayerCharacter::TickPlunge(float DeltaSeconds)
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (bPlungeLanded)
	{
		// Crouched in the crater, then back on your feet (movement cuts the tail short).
		const float Since = float(Now - PlungeLandTime);
		if (Since > 0.75f || (Since > 0.4f && HasRecentMoveInput()))
		{
			if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
			{
				AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
			}
			EndAction();
		}
		return;
	}
	PlungeT += DeltaSeconds / 0.26f;
	const float A = FMath::Clamp(PlungeT, 0.f, 1.f);
	const FVector P = FMath::Lerp(PlungeFrom, PlungeTo, FMath::InterpEaseIn(0.f, 1.f, A, 2.5f));
	SetActorLocation(P, false, nullptr, ETeleportType::TeleportPhysics);
	if (A < 1.f)
	{
		return;
	}

	// Landing: area slam around the impact point.
	bPlungeLanded = true;
	PlungeLandTime = Now;
	bInvulnerable = false;
	GetCharacterMovement()->SetMovementMode(MOVE_Walking);
	UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
	if (AnimInstance)
	{
		AnimInstance->SetRootMotionMode(ERootMotionMode::RootMotionFromMontagesOnly);
		if (CurrentMontage && AnimInstance->Montage_GetPosition(CurrentMontage) < 0.84f)
		{
			AnimInstance->Montage_SetPosition(CurrentMontage, 0.84f); // impact pose on touchdown
		}
	}
	const float HalfHeight = GetCapsuleComponent()->GetScaledCapsuleHalfHeight();
	const FVector Ground = GetActorLocation() - FVector(0.f, 0.f, HalfHeight - 3.f);
	int32 Hits = 0;
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		ABFEnemyBase* Enemy = *It;
		if (Enemy->IsDead())
		{
			continue;
		}
		const float Reach = 230.f + Enemy->GetCapsuleComponent()->GetScaledCapsuleRadius();
		const FVector EnemyFeet = Enemy->GetActorLocation() - FVector(0.f, 0.f, Enemy->GetHalfHeight());
		if (FVector::Dist2D(Enemy->GetActorLocation(), Ground) > Reach || FMath::Abs(EnemyFeet.Z - Ground.Z) > 250.f)
		{
			continue;
		}
		FBFHitInfo Hit;
		Hit.Damage = 26.f;
		Hit.PostureDamage = 20.f;
		Hit.StanceDamage = 35.f;
		Hit.bFinisher = true;
		Hit.bHeavy = true;
		Hit.Weight = EBFHitWeight::Finisher;
		Hit.ImpactPoint = Enemy->GetActorLocation() - (Enemy->GetActorLocation() - Ground).GetSafeNormal2D() * Enemy->GetCapsuleComponent()->GetScaledCapsuleRadius();
		Hit.Instigator = this;
		if (!Enemy->ReceiveHit(Hit))
		{
			continue;
		}
		++Hits;
		Enemy->ApplyHitstop(0.18f);
		SpawnVfx(HitVfx, Hit.ImpactPoint, (Enemy->GetActorLocation() - Ground).GetSafeNormal2D().Rotation(), 1.6f);
		UE_LOG(LogTemp, Display, TEXT("BFTEST hit chain=P idx=0 win=0 dmg=%.0f weight=%d armored=%d target_hp=%.0f stance=%.0f"),
			Hit.Damage, int32(Hit.Weight), Enemy->WasLastHitArmored() ? 1 : 0, Enemy->GetHealth(), Enemy->GetStance());
	}
	ApplyHitstop(0.1f);
	ImpactFrame();
	AddCameraShake(14.f, 0.4f, FVector::DownVector, 6.f);
	SpawnVfx(HitVfx, Ground + FVector(0.f, 0.f, 25.f), FRotator(90.f, 0.f, 0.f), 1.8f);
	ABFRingFX::SpawnGround(GetWorld(), Ground, FLinearColor(0.3f, 0.75f, 1.f), 40.f, 480.f, 0.4f);
	ABFRingFX::SpawnGround(GetWorld(), Ground + FVector(0.f, 0.f, 1.f), FLinearColor::White, 20.f, 260.f, 0.25f);
	if (HitSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, HitSound, Ground, 1.5f, 0.65f);
	}
	if (BlockSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, BlockSound, Ground, 0.8f, 0.6f);
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST plunge landed hits=%d"), Hits);
	if (!AutoTestMode.IsEmpty())
	{
		AutoTestShot(TEXT("p_plunge"));
		PendingShotName = TEXT("p_plunge_post");
		PendingShotTime = AutoTestTime + 0.12f;
	}
}

