// Lock-on

void ABFPlayerCharacter::OnLockPressed()
{
	if (bCinematic)
	{
		return;
	}
	SetLockTarget(bLockedOn ? nullptr : FindLockCandidate(0.f));
}

void ABFPlayerCharacter::OnLockSwitch(const FInputActionValue& Value)
{
	const float V = Value.Get<float>();
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (!bLockedOn || FMath::Abs(V) < 0.1f || Now - LockSwitchTime < 0.25)
	{
		return;
	}
	LockSwitchTime = Now;
	if (ABFEnemyBase* Next = FindLockCandidate(V > 0.f ? 1.f : -1.f))
	{
		SetLockTarget(Next);
	}
}

void ABFPlayerCharacter::SetLockTarget(ABFEnemyBase* Target)
{
	LockTarget = Target;
	bLockedOn = Target != nullptr;
	// Locked: the body keeps facing the target and strafes (directional blend space at strafe speed).
	UCharacterMovementComponent* Movement = GetCharacterMovement();
	Movement->bOrientRotationToMovement = !bLockedOn;
	Movement->MaxWalkSpeed = bLockedOn ? 427.f : BaseWalkSpeed;
	if (UBFAnimInstance* Anim = Cast<UBFAnimInstance>(GetMesh()->GetAnimInstance()))
	{
		Anim->bStrafing = bLockedOn;
	}
	if (bLockedOn)
	{
		LockTime = GetWorld()->GetRealTimeSeconds();
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST lockon %s target=%s"), bLockedOn ? TEXT("on") : TEXT("off"), Target ? *Target->GetName() : TEXT("none"));
}

ABFEnemyBase* ABFPlayerCharacter::FindLockCandidate(float SwitchDir) const
{
	const APlayerController* PC = Cast<APlayerController>(GetController());
	const FRotator ViewYaw(0.f, PC ? PC->GetControlRotation().Yaw : GetActorRotation().Yaw, 0.f);
	const FVector ViewFwd = ViewYaw.Vector();
	const FVector ViewRight = FRotationMatrix(ViewYaw).GetUnitAxis(EAxis::Y);
	const FVector Eye = FollowCamera->GetComponentLocation();
	const ABFEnemyBase* Current = SwitchDir != 0.f ? LockTarget.Get() : nullptr;
	const float CurrentSide = Current ? FVector::DotProduct(ViewRight, (Current->GetActorLocation() - Eye).GetSafeNormal2D()) : 0.f;

	ABFEnemyBase* Best = nullptr;
	float BestScore = TNumericLimits<float>::Max();
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		ABFEnemyBase* Enemy = *It;
		if (Enemy->IsDead() || Enemy == Current)
		{
			continue;
		}
		const float Dist = FVector::Dist2D(Enemy->GetActorLocation(), GetActorLocation());
		if (Dist > 2500.f)
		{
			continue;
		}
		const FVector Dir = (Enemy->GetActorLocation() - Eye).GetSafeNormal2D();
		const float Front = FVector::DotProduct(ViewFwd, Dir);
		float Score;
		if (SwitchDir == 0.f)
		{
			// Fresh lock: whatever is closest to the screen centre, nearer ones first.
			if (Front < 0.2f && Dist > 600.f)
			{
				continue;
			}
			Score = (1.f - Front) * 1500.f + Dist;
		}
		else
		{
			// Switch: the next target in that screen direction.
			const float Delta = (FVector::DotProduct(ViewRight, Dir) - CurrentSide) * SwitchDir;
			if (Delta <= 0.02f || Front < -0.2f)
			{
				continue;
			}
			Score = Delta * 1000.f + Dist * 0.2f;
		}
		if (Score < BestScore)
		{
			BestScore = Score;
			Best = Enemy;
		}
	}
	return Best;
}

void ABFPlayerCharacter::TickLockOn(float RealDelta)
{
	if (!bLockedOn)
	{
		if (AutoTestMode != TEXT("gallery") && AutoTestMode != TEXT("trail") && !CameraBoom->SocketOffset.Equals(BoomBaseSocket, 0.5f))
		{
			CameraBoom->SocketOffset = FMath::VInterpTo(CameraBoom->SocketOffset, BoomBaseSocket, RealDelta, 4.f);
		}
		return;
	}
	ABFEnemyBase* Target = LockTarget.Get();
	if (!Target || Target->IsDead() || FVector::Dist2D(Target->GetActorLocation(), GetActorLocation()) > 3000.f)
	{
		// Target gone: hop to the next one in view, or drop the lock.
		SetLockTarget(Target && Target->IsDead() ? FindLockCandidate(0.f) : nullptr);
		return;
	}
	if (bClashCam || bCinematic || bGrabbed)
	{
		return; // those cameras own the view
	}

	// Shoulder camera sits a little wider and higher while locked, so the player covers less of the target.
	// Showcase recording (9:16): no shoulder shift, the player stays in the middle of the frame.
	CameraBoom->SocketOffset = FMath::VInterpTo(CameraBoom->SocketOffset, BoomBaseSocket + (IsShowGameplay() ? FVector::ZeroVector : FVector(0.f, 25.f, 22.f)), RealDelta, 4.f);

	// Camera: aim at the target, pitched down a little so the player stays in frame (more when close).
	if (APlayerController* PC = Cast<APlayerController>(GetController()))
	{
		const FVector Aim = GetLockPoint();
		const float Dist = FVector::Dist2D(Aim, GetActorLocation());
		FRotator Want = (Aim - CameraBoom->GetComponentLocation()).Rotation();
		Want.Pitch = FMath::Clamp(Want.Pitch - FMath::GetMappedRangeValueClamped(FVector2D(150.f, 800.f), FVector2D(22.f, 10.f), Dist), -40.f, IsShowGameplay() ? -6.f : 12.f);
		Want.Roll = 0.f;
		PC->SetControlRotation(FMath::RInterpTo(PC->GetControlRotation(), Want, RealDelta, 8.f));
	}

	// Body faces the target while free on the ground or guarding (actions orient themselves).
	if (((State == EBFPlayerState::Free && !GetCharacterMovement()->IsFalling()) || State == EBFPlayerState::Guarding) && !bSprinting)
	{
		const FVector To = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
		if (!To.IsNearlyZero())
		{
			const float BodyDelta = GetWorld()->GetDeltaSeconds() * CustomTimeDilation;
			SetActorRotation(FMath::RInterpConstantTo(GetActorRotation(), FRotator(0.f, To.Rotation().Yaw, 0.f), BodyDelta, 720.f));
		}
	}
}

void ABFPlayerCharacter::TickMagicCam(float RealDelta)
{
	ABFEnemyBase* Caster = nullptr;
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		if (!It->IsDead() && It->HasMagicPending() && FVector::Dist2D(It->GetActorLocation(), GetActorLocation()) < 4000.f)
		{
			Caster = *It;
			break;
		}
	}
	const bool bWant = Caster && !bClashCam && !bCinematic && !bGrabbed && !bStruggle;
	if (Caster)
	{
		MagicCamBoss = Caster;
	}
	const float Prev = MagicCamAlpha;
	// In over ~0.6 s, back out over ~0.8 s.
	MagicCamAlpha = FMath::FInterpConstantTo(MagicCamAlpha, bWant ? 1.f : 0.f, RealDelta, bWant ? 1.7f : 1.25f);
	if (MagicCamAlpha <= 0.f && Prev <= 0.f)
	{
		return;
	}
	if ((Prev <= 0.f) != (MagicCamAlpha <= 0.f) || (Prev < 1.f) != (MagicCamAlpha < 1.f))
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST magic cam alpha=%.0f (%s)"), MagicCamAlpha, MagicCamAlpha > Prev ? TEXT("in") : TEXT("out"));
	}
	const float E = FMath::SmoothStep(0.f, 1.f, MagicCamAlpha);
	ABFEnemyBase* Boss = MagicCamBoss.Get();
	const FVector BoomLoc = CameraBoom->GetComponentLocation();
	const FVector SideAxis = Boss ? FVector::CrossProduct(FVector::UpVector, (Boss->GetActorLocation() - GetActorLocation()).GetSafeNormal2D()) : GetActorRightVector();
	constexpr float Lift = 260.f;
	if (bWant && Boss)
	{
		// Pick a framing whose sight lines (camera -> boss, camera -> player) clear the pillars: shift
		// the pivot sideways (the boss stays centred), shorten the arm only if nothing is clear.
		MagicCamCheckTimer -= RealDelta;
		if (MagicCamCheckTimer <= 0.f || Prev <= 0.f)
		{
			MagicCamCheckTimer = 0.3f;
			FCollisionQueryParams Params(SCENE_QUERY_STAT(BFMagicCam), false, this);
			Params.AddIgnoredActor(Boss);
			auto Clear = [&](float Side, float Arm)
			{
				const FVector Pivot = BoomLoc + FVector(0.f, 0.f, Lift) + SideAxis * Side;
				const FVector Cam = Pivot - (Boss->GetActorLocation() - Pivot).GetSafeNormal() * Arm;
				const FCollisionShape Ball = FCollisionShape::MakeSphere(25.f);
				FHitResult Hit;
				return !GetWorld()->SweepSingleByChannel(Hit, Cam, Boss->GetActorLocation(), FQuat::Identity, ECC_Visibility, Ball, Params)
					&& !GetWorld()->SweepSingleByChannel(Hit, Cam, GetActorLocation() + FVector(0.f, 0.f, 40.f), FQuat::Identity, ECC_Visibility, Ball, Params);
			};
			bool bFound = false;
			for (const float Arm : { 1300.f, 900.f })
			{
				for (const float Side : { MagicCamSide, 0.f, 300.f, -300.f, 600.f, -600.f })
				{
					if (Clear(Side, Arm))
					{
						if (Side != MagicCamSide || Arm != MagicCamArm)
						{
							UE_LOG(LogTemp, Display, TEXT("BFTEST magic cam framing side=%.0f arm=%.0f"), Side, Arm);
						}
						MagicCamSide = Side;
						MagicCamArm = Arm;
						bFound = true;
						break;
					}
				}
				if (bFound)
				{
					break;
				}
			}
			if (!bFound)
			{
				MagicCamSide = 0.f;
				MagicCamArm = 600.f;
			}
		}
	}
	if (!bClashCam && !bCinematic)
	{
		// The arena's edge sits behind the player: without this the spring arm folds back in.
		CameraBoom->bDoCollisionTest = MagicCamAlpha <= 0.f;
		CameraBoom->TargetArmLength = FMath::FInterpTo(CameraBoom->TargetArmLength, FMath::Lerp(BaseArmLength, MagicCamArm, E), RealDelta, 6.f);
		// Raised (and maybe shifted) pivot: the camera looks over the player's head, past the pillars.
		const FVector WantOffset = IsShowGameplay() ? FVector::ZeroVector : (FVector(0.f, 0.f, Lift) + SideAxis * MagicCamSide) * E;
		CameraBoom->TargetOffset = MagicCamAlpha <= 0.f ? FVector::ZeroVector : FMath::VInterpTo(CameraBoom->TargetOffset, WantOffset, RealDelta, 4.f);
	}
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!Boss || !PC || !bWant)
	{
		return; // easing out: the arm shrinks back, lock-on (or the player) takes the aim again
	}
	// Camera, boom pivot and boss on one line: the boss sits in the middle of the frame.
	FRotator Want = (Boss->GetActorLocation() - (CameraBoom->GetComponentLocation() + CameraBoom->TargetOffset)).Rotation();
	// Showcase: never look up past level, or the long arm swings the camera under the floor.
	Want.Pitch = FMath::Clamp(Want.Pitch, -40.f, IsShowGameplay() ? -6.f : 25.f);
	Want.Roll = 0.f;
	PC->SetControlRotation(FMath::RInterpTo(PC->GetControlRotation(), Want, RealDelta, 2.f + 5.f * E));
}

ABFEnemyBase* ABFPlayerCharacter::GetFacingTarget(float Range) const
{
	if (bLockedOn && LockTarget.IsValid() && !LockTarget->IsDead())
	{
		return LockTarget.Get();
	}
	return FindSoftLockTarget(Range);
}

FVector ABFPlayerCharacter::GetLockPoint() const
{
	const ABFEnemyBase* Target = LockTarget.Get();
	return Target ? Target->GetActorLocation() + FVector(0.f, 0.f, Target->GetLockHeight()) : FVector::ZeroVector;
}

float ABFPlayerCharacter::GetLockPop() const
{
	return bLockedOn ? PulseFrom(LockTime, 0.35f) : 0.f;
}

// ---------------------------------------------------------------------------------------------
// Dodge charges

float ABFPlayerCharacter::GetDashRefill01() const
{
	if (DashCharges >= BFCombat::MaxDashCharges)
	{
		return 1.f;
	}
	return FMath::Clamp(float(GetWorld()->GetRealTimeSeconds() - DashReloadStartTime) / BFCombat::DashRefillDelay, 0.f, 1.f);
}

int32 ABFPlayerCharacter::GetRecentDashCount(float Window) const
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	int32 Count = 0;
	for (const double T : DashHistory)
	{
		Count += Now - T <= Window ? 1 : 0;
	}
	return Count;
}

void ABFPlayerCharacter::RewardPerfectDodge()
{
	// A perfect dodge refunds the roll it used and earns one more (once per roll).
	if (bDashRewarded)
	{
		return;
	}
	bDashRewarded = true;
	const int32 Before = DashCharges;
	DashCharges = FMath::Min(BFCombat::MaxDashCharges, DashCharges + 2);
	DashGainTime = GetWorld()->GetRealTimeSeconds();
	UE_LOG(LogTemp, Display, TEXT("BFTEST dash perfect charges=%d->%d"), Before, DashCharges);
}

float ABFPlayerCharacter::PulseFrom(double Start, float Length) const
{
	const float T = static_cast<float>(GetWorld()->GetRealTimeSeconds() - Start);
	return T < 0.f || T > Length ? 0.f : 1.f - T / Length;
}

bool ABFPlayerCharacter::CanCancelAttack() const
{
	// Outside an open hit window, or once the swing has connected (cancel the rest of it).
	return (ActiveWindow == INDEX_NONE || HitThisWindow.Num() > 0) && !bExecuting;
}

// ---------------------------------------------------------------------------------------------
// Perilous answers

void ABFPlayerCharacter::PerfectJump(ABFEnemyBase* Attacker)
{
	// Jumped the ground wave: a beat of slow motion, then LMB drops onto the boss's head.
	const double Now = GetWorld()->GetRealTimeSeconds();
	WorldSlowMo(0.3f, 0.5f);
	bStompReady = Attacker != nullptr;
	StompReadyUntil = Now + 1.1;
	StompTarget = Attacker;
	const FVector Feet = GetActorLocation() - FVector(0.f, 0.f, GetCapsuleComponent()->GetScaledCapsuleHalfHeight() - 5.f);
	ABFRingFX::SpawnGround(GetWorld(), Feet, BFCombat::PerilousColor(EBFPerilous::Sweep), 30.f, 260.f, 0.35f);
	ABFRingFX::Spawn(GetWorld(), GetActorLocation(), FLinearColor(1.f, 0.9f, 0.5f), 15.f, 160.f, 0.25f);
	SpawnAfterImage();
	AddCameraShake(5.f, 0.2f);
	UE_LOG(LogTemp, Display, TEXT("BFTEST perilous jumped stomp_ready=%d"), bStompReady ? 1 : 0);
	if (!AutoTestMode.IsEmpty())
	{
		AutoTestShot(TEXT("p_jumped"));
	}
}

bool ABFPlayerCharacter::CanStomp() const
{
	const ABFEnemyBase* Target = StompTarget.Get();
	return bStompReady && Target && !Target->IsDead() && State == EBFPlayerState::Free
		&& GetWorld()->GetRealTimeSeconds() <= StompReadyUntil
		&& FVector::Dist2D(Target->GetActorLocation(), GetActorLocation()) <= 650.f;
}

void ABFPlayerCharacter::StartStomp()
{
	ABFEnemyBase* Target = StompTarget.Get();
	if (!Target)
	{
		return;
	}
	bStompReady = false;
	State = EBFPlayerState::Stomping;
	ActiveWindow = INDEX_NONE;
	Buffered = EBuffered::None;
	bInvulnerable = true;
	StompFrom = GetActorLocation();
	StompT = 0.f;
	GetCharacterMovement()->StopMovementImmediately();
	GetCharacterMovement()->SetMovementMode(MOVE_Flying);
	const FVector To = (Target->GetActorLocation() - GetActorLocation()).GetSafeNormal2D();
	SetActorRotation(FRotator(0.f, To.Rotation().Yaw, 0.f));
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		AnimInstance->SetRootMotionMode(ERootMotionMode::IgnoreRootMotion); // the arc is scripted
		if (UAnimMontage* Montage = PlayAnim(StompAnim, 1.6f, 0.05f, 0.25f))
		{
			AnimInstance->Montage_SetPosition(Montage, 0.45f);
		}
	}
	SpawnAfterImage();
	UE_LOG(LogTemp, Display, TEXT("BFTEST stomp start"));
}

void ABFPlayerCharacter::TickStomp(float DeltaSeconds)
{
	ABFEnemyBase* Target = StompTarget.Get();
	StompT += DeltaSeconds / 0.3f;
	auto Finish = [this]()
	{
		bInvulnerable = false;
		GetCharacterMovement()->SetMovementMode(MOVE_Falling);
		if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
		{
			AnimInstance->SetRootMotionMode(ERootMotionMode::RootMotionFromMontagesOnly);
		}
		State = EBFPlayerState::Free;
	};
	if (!Target)
	{
		Finish();
		return;
	}

	// Short arc onto the top of the head.
	const FVector Dir = (Target->GetActorLocation() - StompFrom).GetSafeNormal2D();
	const FVector Top = Target->GetActorLocation() + FVector(0.f, 0.f, Target->GetHalfHeight() + 100.f) - Dir * 35.f;
	const float A = FMath::Clamp(StompT, 0.f, 1.f);
	FVector P = FMath::Lerp(StompFrom, Top, FMath::InterpEaseIn(0.f, 1.f, A, 2.f));
	P.Z += FMath::Sin(A * UE_PI) * 120.f;
	SetActorLocation(P, false, nullptr, ETeleportType::TeleportPhysics);
	if (StompT < 1.f)
	{
		return;
	}

	// Impact: posture crush, stagger, impact frame, then spring off backwards.
	const FVector Head = Top - FVector(0.f, 0.f, 70.f);
	Target->OnStomped(this, 15.f, 55.f);
	ImpactFrame();
	ApplyHitstop(0.12f);
	Target->ApplyHitstop(0.16f);
	AddCameraShake(14.f, 0.4f, FVector::DownVector, 6.f);
	SpawnVfx(HitVfx, Head, FRotator(-90.f, 0.f, 0.f), 1.6f);
	ABFRingFX::Spawn(GetWorld(), Head, BFCombat::PerilousColor(EBFPerilous::Sweep), 30.f, 320.f, 0.35f);
	ABFRingFX::Spawn(GetWorld(), Head, FLinearColor::White, 15.f, 160.f, 0.2f);
	if (HitSound)
	{
		UGameplayStatics::PlaySoundAtLocation(this, HitSound, Head, 1.5f, 0.7f);
	}
	Finish();
	LaunchCharacter(-Dir * 550.f + FVector(0.f, 0.f, 650.f), true, true);
	UE_LOG(LogTemp, Display, TEXT("BFTEST stomp landed boss_hp=%.0f boss_posture=%.0f"), Target->GetHealth(), Target->GetPosture());
	if (!AutoTestMode.IsEmpty())
	{
		AutoTestShot(TEXT("p_stomp"));
	}
}

