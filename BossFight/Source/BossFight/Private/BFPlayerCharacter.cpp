void ABFPlayerCharacter::TickGrabbed()
{
	ABFEnemyBase* By = GrabBy.Get();
	const double Now = GetWorld()->GetRealTimeSeconds();
	const float T = static_cast<float>(Now - GrabStart);
	// Drained three times. Apply every drain that is due first, so a long frame cannot skip one
	// before the throw.
	static constexpr float DrainAt[3] = { 0.35f, 0.65f, 0.95f };
	if (By && !By->IsDead())
	{
		while (GrabTicks < 3 && T >= DrainAt[GrabTicks])
		{
			const float D = GrabDamage / 3.f * BFCombat::TestDamageToPlayer;
			Health = FMath::Max(0.f, Health - D);
			By->OnSiphonDrain(D * 0.8f);
			HurtTime = Now;
			if (HitFlash)
			{
				HitFlash->Flash(BFCombat::PerilousColor(EBFPerilous::Grab), 0.12f, 0.7f);
			}
			ABFRingFX::Spawn(GetWorld(), GetActorLocation() + FVector(0.f, 0.f, 30.f), BFCombat::PerilousColor(EBFPerilous::Grab), 20.f, 140.f, 0.25f);
			AddCameraShake(5.f, 0.15f);
			++GrabTicks;
			UE_LOG(LogTemp, Display, TEXT("BFTEST grab drain %d player_hp=%.0f"), GrabTicks, Health);
			if (Health <= 0.f)
			{
				UE_LOG(LogTemp, Display, TEXT("BFTEST player down (refilled until phase 8)"));
				Health = MaxHealth;
			}
		}
	}
	if (By && !By->IsDead() && T < 1.15f)
	{
		// Pulled up in front of him.
		FVector Hold = By->GetActorLocation() + By->GetActorForwardVector() * 150.f;
		Hold.Z = By->GetActorLocation().Z - By->GetHalfHeight() + 156.f;
		const float A = FMath::Clamp(T / 0.25f, 0.f, 1.f);
		SetActorLocation(FMath::Lerp(GrabFrom, Hold, FMath::InterpEaseOut(0.f, 1.f, A, 2.f)), false, nullptr, ETeleportType::TeleportPhysics);
		SetActorRotation(FRotator(0.f, (-By->GetActorForwardVector()).Rotation().Yaw, 0.f));
		return;
	}

	// Thrown away: knocked down.
	bGrabbed = false;
	GetCharacterMovement()->SetMovementMode(MOVE_Falling);
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		AnimInstance->SetRootMotionMode(ERootMotionMode::RootMotionFromMontagesOnly);
	}
	const FVector Away = By ? (GetActorLocation() - By->GetActorLocation()).GetSafeNormal2D() : -GetActorForwardVector();
	SetActorRotation(FRotator(0.f, (-Away).Rotation().Yaw, 0.f));
	LaunchCharacter(Away * 500.f + FVector(0.f, 0.f, 350.f), true, true);
	StartKnockdown(BlowbackAnim ? BlowbackAnim.Get() : KnockdownAnim.Get(), 0.5f);
	AddCameraShake(10.f, 0.35f, Away, 3.f);
	UE_LOG(LogTemp, Display, TEXT("BFTEST grab release player_hp=%.0f"), Health);
}

void ABFPlayerCharacter::FellOutOfWorld(const UDamageType& DmgType)
{
	// The default destroys the pawn, which left the fight with nobody in it.
	RecoverFromFall();
}

void ABFPlayerCharacter::RecoverFromFall()
{
	// Back onto the last solid ground, a step further in (toward the enemy) so we do not land on
	// the lip again, with a small penalty instead of a dead end.
	FVector Back = LastSafeGround;
	for (TActorIterator<ABFEnemyBase> It(GetWorld()); It; ++It)
	{
		const FVector ToEnemy = It->GetActorLocation() - Back;
		if (!It->IsDead() && ToEnemy.Size2D() > 350.f)
		{
			Back += ToEnemy.GetSafeNormal2D() * 120.f;
		}
		break;
	}
	GetCharacterMovement()->StopMovementImmediately();
	SetActorLocation(Back + FVector(0.f, 0.f, 5.f), false, nullptr, ETeleportType::TeleportPhysics);
	GetCharacterMovement()->SetMovementMode(MOVE_Walking);
	Health = FMath::Max(1.f, Health - 15.f);
	HurtTime = GetWorld()->GetRealTimeSeconds();
	if (HitFlash)
	{
		HitFlash->Flash(FLinearColor(1.f, 0.2f, 0.15f), 0.1f, 0.4f);
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST fell off arena, back on ground hp=%.0f"), Health);
}

