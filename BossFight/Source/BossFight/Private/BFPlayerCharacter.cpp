ABFPlayerCharacter::ABFPlayerCharacter()
{
	PrimaryActorTick.bCanEverTick = true;

	GetCapsuleComponent()->InitCapsuleSize(42.f, 96.f);

	// Camera turns the view; the body turns toward where it moves.
	bUseControllerRotationPitch = false;
	bUseControllerRotationYaw = false;
	bUseControllerRotationRoll = false;

	UCharacterMovementComponent* Movement = GetCharacterMovement();
	Movement->bOrientRotationToMovement = true;
	Movement->RotationRate = FRotator(0.f, 900.f, 0.f);
	// Matches the run clip's native root speed (488 cm/s) so the feet do not slide.
	Movement->MaxWalkSpeed = 488.f;
	Movement->MaxAcceleration = 2400.f;
	// Higher friction re-aims velocity toward the new input faster, so turns do not drift.
	Movement->GroundFriction = 10.f;
	Movement->JumpZVelocity = 650.f;
	Movement->AirControl = 0.35f;
	Movement->GravityScale = 1.6f;
	Movement->BrakingDecelerationWalking = 2000.f;

	// Mannequin mesh faces +Y in its own space, so rotate it to face the capsule's +X.
	GetMesh()->SetRelativeLocationAndRotation(FVector(0.f, 0.f, -96.f), FRotator(0.f, -90.f, 0.f));

	static ConstructorHelpers::FObjectFinder<USkeletalMesh> MeshFinder(BFPaths::PlayerMesh);
	if (MeshFinder.Succeeded())
	{
		GetMesh()->SetSkeletalMesh(MeshFinder.Object);
	}

	static ConstructorHelpers::FClassFinder<UAnimInstance> AnimFinder(BFPaths::PlayerAnimBP);
	if (AnimFinder.Succeeded())
	{
		GetMesh()->SetAnimInstanceClass(AnimFinder.Class);
	}

	// Anime body on top of the mannequin: same component space (both face +Y), posed by runtime retarget.
	// Its assets load in PostInitializeComponents: here, during module startup, the IKRig runtime and the
	// BossFightAnimGraph nodes (her hair/cloth post-process ABP) are not loaded yet and the ABPs load broken.
	AnimeBody = CreateDefaultSubobject<USkeletalMeshComponent>(TEXT("AnimeBody"));
	AnimeBody->SetupAttachment(GetMesh());
	AnimeBody->SetCollisionEnabled(ECollisionEnabled::NoCollision);

	// Sword offset copied from the pack's Sword_SK_Mannequin_Blueprint (moved to her hand when she loads).
	Sword = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("Sword"));
	Sword->SetupAttachment(GetMesh(), TEXT("hand_r"));
	Sword->SetRelativeLocationAndRotation(FVector(0.715f, 8.327f, 0.512f), FRotator(-20.079f, -92.961f, -170.420f));
	Sword->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	static ConstructorHelpers::FObjectFinder<UStaticMesh> SwordFinder(BFPaths::SwordMesh);
	if (SwordFinder.Succeeded())
	{
		Sword->SetStaticMesh(SwordFinder.Object);
	}

	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(RootComponent);
	CameraBoom->TargetArmLength = 420.f;
	CameraBoom->SocketOffset = FVector(0.f, 45.f, 60.f);
	CameraBoom->bUsePawnControlRotation = true;
	CameraBoom->bEnableCameraLag = true;
	CameraBoom->CameraLagSpeed = 12.f;

	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;
	FollowCamera->SetFieldOfView(80.f);

	// Clash-cam look (blended in by PostProcessBlendWeight only during a parry cinematic):
	// ink outlines, stronger contrast, vignette, chromatic fringe and heavy motion blur on the whips.
	{
		FPostProcessSettings& PP = FollowCamera->PostProcessSettings;
		PP.bOverride_SceneFringeIntensity = true;
		PP.SceneFringeIntensity = 1.2f;
		PP.bOverride_VignetteIntensity = true;
		PP.VignetteIntensity = 0.75f;
		PP.bOverride_ColorContrast = true;
		PP.ColorContrast = FVector4(1.15f, 1.15f, 1.15f, 1.f);
		PP.bOverride_ColorSaturation = true;
		PP.ColorSaturation = FVector4(1.2f, 1.2f, 1.25f, 1.f);
		PP.bOverride_MotionBlurAmount = true;
		PP.MotionBlurAmount = 1.f;
		PP.bOverride_MotionBlurMax = true;
		PP.MotionBlurMax = 12.f;
		InkMaterial = FindAsset<UMaterialInterface>(BFPaths::InkMat);
		if (InkMaterial)
		{
			PP.WeightedBlendables.Array.Add(FWeightedBlendable(1.f, InkMaterial));
		}
		FollowCamera->PostProcessBlendWeight = 0.f;
	}

	// Combo data. Hit windows come from hand_r speed peaks (Scripts/11_anim_analyze.py).
	// Six-hit light string. The swing direction alternates every hit (down-cut, flat, rising right, rising
	// cross, rise + double down-cut, spinning flurry); hit 3 is the slower "breath" before the run-up to the
	// finisher. Windows for the Shockwave halves come from Scripts' hand_r speed probe (combo_dir).
	LightChain = {
		MakeAttack(TEXT("combo01_1"), {{0.22f, 0.45f}}, 0.50f, 8.f, 6.f, 1.15f, false),
		MakeAttack(TEXT("combo01_2"), {{0.22f, 0.55f}}, 0.60f, 10.f, 8.f, 1.15f, false),
		MakeAttack(TEXT("Attack_Shockwave_1"), {{0.48f, 0.70f}}, 0.78f, 11.f, 9.f, 1.25f, false),
		MakeAttack(TEXT("Attack_Shockwave_2"), {{0.24f, 0.52f}}, 0.60f, 12.f, 10.f, 1.15f, false),
		MakeAttack(TEXT("combo01_3"), {{0.12f, 0.32f}, {0.48f, 0.75f}}, 0.92f, 14.f, 12.f, 1.1f, false),
		MakeAttack(TEXT("combo02_3"), {{0.12f, 0.88f}}, 1.10f, 24.f, 24.f, 1.05f, true),
	};
	HeavyChain = {
		MakeAttack(TEXT("combo02_1"), {{0.08f, 0.50f}}, 0.60f, 16.f, 14.f, 1.0f, false),
		MakeAttack(TEXT("combo02_2"), {{0.25f, 0.68f}}, 0.80f, 20.f, 18.f, 1.0f, false),
		MakeAttack(TEXT("combo02_3"), {{0.12f, 0.88f}}, 1.10f, 30.f, 30.f, 1.0f, true),
	};
	for (const FBFAttackDef& Def : LightChain)
	{
		LightAnims.Add(FindAnim(Def.AnimPath));
	}
	for (const FBFAttackDef& Def : HeavyChain)
	{
		HeavyAnims.Add(FindAnim(Def.AnimPath));
	}
	// Air combo (Space, then LMB x3): Air_Combo01_Z0_1 and _2 chain end to start, then Air_Attack04_Z0's
	// big diagonal cut as the finisher (Air_Combo01_Z0_3 leaps a metre up and spins: it cut over and
	// behind the target). Windows from hand_r speed; the clips' own forward lunge is ignored in the air.
	AirChain = {
		MakeAttack(TEXT("Air_Combo01_Z0_1"), {{0.23f, 0.43f}}, 0.50f, 9.f, 7.f, 1.2f, false),
		MakeAttack(TEXT("Air_Combo01_Z0_2"), {{0.40f, 0.70f}}, 0.75f, 11.f, 9.f, 1.2f, false),
		MakeAttack(TEXT("Air_Attack04_Z0"), {{0.10f, 0.47f}}, 0.90f, 16.f, 14.f, 1.0f, true),
	};
	for (const FBFAttackDef& Def : AirChain)
	{
		AirAnims.Add(FindAnim(Def.AnimPath));
	}
	KnockUpAnim = FindAnim(TEXT("hit_bound_up_high"));
	DashAnim = FindAnim(TEXT("Rolling"));
	for (const TCHAR* Path : BFPaths::SlideAnims)
	{
		SlideAnims.Add(FindAsset<UAnimSequence>(Path));
	}
	SmearMaterial = FindAsset<UMaterialInterface>(BFPaths::SmearMat);

	AfterImageMaterial = FindAsset<UMaterialInterface>(BFPaths::AfterImageMat);
	HitVfx = FindAsset<UNiagaraSystem>(BFPaths::HitVfx);
	BlockVfx = FindAsset<UNiagaraSystem>(BFPaths::BlockVfx);
	BlockSound = FindAsset<USoundBase>(BFPaths::BlockSound);
	ParrySound = FindAsset<USoundBase>(BFPaths::ParrySound);
	GuardAnim = FindAnim(TEXT("depence"));
	for (const TCHAR* Path : BFPaths::AvoidAnims)
	{
		AvoidAnims.Add(FindAsset<UAnimSequence>(Path));
	}
	RoarHitAnim = AvoidAnims[1];
	HitReactAnims = { FindAnim(TEXT("hit_light_F_head")), FindAnim(TEXT("hit_light_L_body")), FindAnim(TEXT("hit_light_R_body")) };
	ExecutionAnim = FindAnim(TEXT("combo02_3"));
	KnockdownAnim = FindAnim(TEXT("hit_knockdown01"));
	GetUpAnim = FindAnim(TEXT("rise_1")); // hit_down_up is a floor bounce, not a get-up
	DownLoopAnim = FindAnim(TEXT("hit_down_idle_up"));
	BlowbackAnim = FindAnim(TEXT("hit_knockdown02"));
	HitFlash = CreateDefaultSubobject<UBFHitFlashComponent>(TEXT("HitFlash"));
	HitSound = FindAsset<USoundBase>(BFPaths::HitSound);
	SwingSound = FindAsset<USoundBase>(BFPaths::SwingSound);
	StompAnim = FindAnim(TEXT("Air_Down_Attack_Z0"));
	GrabbedAnim = FindAnim(TEXT("hit_air_pulled"));
	TrailVfx = FindAsset<UNiagaraSystem>(TEXT("/Game/SlashHitVFX/NS/NS_Trail_Sword.NS_Trail_Sword"));
}

void ABFPlayerCharacter::BeginPlay()
{
	Super::BeginPlay();
	if (AnimeBody && AnimeBody->GetSkeletalMeshAsset())
	{
		// Her pose is read from the mannequin, so the mannequin must be evaluated first.
		AnimeBody->AddTickPrerequisiteComponent(GetMesh());
		if (UMaterialInterface* Hidden = LoadObject<UMaterialInterface>(nullptr, BFPaths::AnimeHiddenMat))
		{
			const int32 Slot = AnimeBody->GetMaterialIndex(FName(BFPaths::AnimeHiltSlot));
			if (Slot != INDEX_NONE)
			{
				AnimeBody->SetMaterial(Slot, Hidden);
			}
		}
		if (HitFlash)
		{
			HitFlash->SetTarget(AnimeBody);
		}
		UE_LOG(LogTemp, Display, TEXT("BFTEST anime body on, anim=%s"), AnimeBody->GetAnimInstance() ? *AnimeBody->GetAnimInstance()->GetClass()->GetName() : TEXT("none"));
	}
	// Wade through the Fluid Flux river: push the water and leave ripples.
	BFFluxWater::AddInteraction(this, 40.f);

	if (FParse::Param(FCommandLine::Get(), TEXT("BFAutoTest")))
	{
		AutoTestMode = TEXT("move");
	}
	FParse::Value(FCommandLine::Get(), TEXT("BFAutoTest="), AutoTestMode);

	CameraBaseOffset = FollowCamera->GetRelativeLocation();
	BoomBaseSocket = CameraBoom->SocketOffset;
	BaseArmLength = CameraBoom->TargetArmLength;
	// Walking or rolling stops at the arena edge (jumps and knockbacks can still go over it).
	GetCharacterMovement()->bCanWalkOffLedges = false;
	LastSafeGround = GetActorLocation();
	CameraBaseFov = FollowCamera->FieldOfView;

	// Pre-warm combat effects far below the arena so the first parry/hit is not invisible
	// while its shaders and assets finish loading.
	const FVector Hidden(0.f, 0.f, -20000.f);
	SpawnVfx(HitVfx, Hidden, FRotator::ZeroRotator);
	SpawnVfx(BlockVfx, Hidden, FRotator::ZeroRotator);
	ABFRingFX::Spawn(GetWorld(), Hidden, FLinearColor::White, 10.f, 20.f, 0.5f);
	// Same for the clash-cam post-process: render it at an invisible weight for a few seconds.
	FollowCamera->PostProcessBlendWeight = 0.001f;
	InkPrewarmEnd = GetWorld()->GetRealTimeSeconds() + 3.0;

	// Blade segment along the sword mesh's longest bounds axis.
	if (const UStaticMesh* SwordMesh = Sword->GetStaticMesh())
	{
		const FBox Box = SwordMesh->GetBoundingBox();
		const FVector Extent = Box.GetExtent();
		const int32 Axis = Extent.X >= Extent.Y && Extent.X >= Extent.Z ? 0 : (Extent.Y >= Extent.Z ? 1 : 2);
		BladeLocalA = Box.GetCenter();
		BladeLocalB = Box.GetCenter();
		BladeLocalA[Axis] = Box.Min[Axis];
		BladeLocalB[Axis] = Box.Max[Axis];
		// A is the tip: the end farther from the grip (the mesh origin). The pack sword's tip is at Min,
		// the swordswoman's at Max.
		if (BladeLocalB.Size() > BladeLocalA.Size())
		{
			Swap(BladeLocalA, BladeLocalB);
		}
	}

	if (const APlayerController* PC = Cast<APlayerController>(GetController()))
	{
		if (UEnhancedInputLocalPlayerSubsystem* Subsystem = ULocalPlayer::GetSubsystem<UEnhancedInputLocalPlayerSubsystem>(PC->GetLocalPlayer()))
		{
			BuildInput();
			Subsystem->AddMappingContext(MappingContext, 0);
		}
	}

	BaseWalkSpeed = GetCharacterMovement()->MaxWalkSpeed;

	// Smears: one ribbon for the sword's slash arc, thin streaks from the head, hands and feet for
	// dashes and sprinting (world-space procedural ribbons, see UBFSmearTrail).
	if (SmearMaterial)
	{
		auto MakeSmear = [this](const TCHAR* Name, const FLinearColor& Color, float Intensity, float Life)
		{
			UBFSmearTrail* Trail = NewObject<UBFSmearTrail>(this, Name);
			Trail->RegisterComponent();
			Trail->Setup(SmearMaterial, Color, Intensity, Life);
			return Trail;
		};
		SwordSmear = MakeSmear(TEXT("SwordSmear"), FLinearColor(0.35f, 0.8f, 1.f), 5.f, 0.16f);
		for (int32 I = 0; I < 6; ++I)
		{
			SpeedStreaks.Add(MakeSmear(*FString::Printf(TEXT("SpeedStreak%d"), I), FLinearColor(0.45f, 0.85f, 1.f), 2.f, 0.2f));
			SpeedStreaks.Last()->SetScalar(TEXT("Outer"), 0.f);
		}
	}

	// Impact frames: an unbound post-process (stark monochrome, hard contrast) switched on for a few
	// frames when a big hit lands.
	{
		FActorSpawnParameters Params;
		Params.SpawnCollisionHandlingOverride = ESpawnActorCollisionHandlingMethod::AlwaysSpawn;
		ImpactVolume = GetWorld()->SpawnActor<APostProcessVolume>(APostProcessVolume::StaticClass(), FTransform::Identity, Params);
		if (ImpactVolume)
		{
			ImpactVolume->bUnbound = true;
			ImpactVolume->Priority = 100.f;
			ImpactVolume->BlendWeight = 0.f;
			FPostProcessSettings& S = ImpactVolume->Settings;
			S.bOverride_ColorSaturation = true;
			S.ColorSaturation = FVector4(0.f, 0.f, 0.f, 1.f);
			S.bOverride_ColorContrast = true;
			S.ColorContrast = FVector4(2.4f, 2.4f, 2.4f, 1.f);
			S.bOverride_ColorGain = true;
			S.ColorGain = FVector4(1.3f, 1.3f, 1.3f, 1.f);
			S.bOverride_VignetteIntensity = true;
			S.VignetteIntensity = 1.2f;
		}
	}

	// Sword trail: ribbon VFX attached at the blade tip (BladeLocalA; B is the pommel end) with local Z
	// pointing out along the blade, so the ribbon's width (the system's AxisOffset is local -Z) runs
	// from the tip back down the blade. Checked with -BFAutoTest=trail. It runs only around swing
	// windows (UpdateSwordTrail).
	if (TrailVfx && Sword->GetStaticMesh())
	{
		FVector Axis = (BladeLocalA - BladeLocalB).GetSafeNormal();
		if (FParse::Param(FCommandLine::Get(), TEXT("BFTrailFlip")))
		{
			Axis = -Axis;
		}
		FRotator Rot = FRotationMatrix::MakeFromZ(Axis).Rotator();
		float AttachAt = 0.f;
		FParse::Value(FCommandLine::Get(), TEXT("BFTrailAt="), AttachAt);
		FString RotArg;
		if (FParse::Value(FCommandLine::Get(), TEXT("BFTrailRot="), RotArg))
		{
			TArray<FString> Parts;
			RotArg.ParseIntoArray(Parts, TEXT(","));
			if (Parts.Num() == 3)
			{
				Rot = (FRotator(FCString::Atof(*Parts[0]), FCString::Atof(*Parts[1]), FCString::Atof(*Parts[2])).Quaternion() * Rot.Quaternion()).Rotator();
			}
		}
		SwordTrail = UNiagaraFunctionLibrary::SpawnSystemAttached(TrailVfx, Sword, NAME_None, FMath::Lerp(BladeLocalA, BladeLocalB, AttachAt), Rot,
			EAttachLocation::KeepRelativeOffset, false, false);
		if (SwordTrail)
		{
			const float BladeLen = FVector::Dist(BladeLocalA, BladeLocalB) * Sword->GetComponentScale().X;
			float Width = BladeLen * 0.9f;
			FParse::Value(FCommandLine::Get(), TEXT("BFTrailWidth="), Width);
			SwordTrail->SetVariableFloat(TEXT("Width"), Width);
			SwordTrail->SetVariableFloat(TEXT("Life"), 0.3f);
			SwordTrail->SetVariableFloat(TEXT("AllSizeScale"), 1.f);
			// Test overrides: -BFTrailF=Name=Value;Name=Value
			FString Overrides;
			if (FParse::Value(FCommandLine::Get(), TEXT("BFTrailF="), Overrides, false))
			{
				TArray<FString> Pairs;
				Overrides.ParseIntoArray(Pairs, TEXT(";"));
				for (const FString& Pair : Pairs)
				{
					FString Name, Value;
					if (Pair.Split(TEXT("="), &Name, &Value))
					{
						SwordTrail->SetVariableFloat(FName(*Name), FCString::Atof(*Value));
					}
				}
			}
			UE_LOG(LogTemp, Display, TEXT("BFTEST sword trail ready width=%.0f"), Width);
		}
	}
}

