void ABFPlayerCharacter::StartRoarKnockback(const FVector& From)
{
	if (bGrabbed || State == EBFPlayerState::Clashing)
	{
		return;
	}
	FVector Away = (GetActorLocation() - From).GetSafeNormal2D();
	if (Away.IsNearlyZero())
	{
		Away = -GetActorForwardVector();
	}
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		AnimInstance->SetRootMotionMode(ERootMotionMode::RootMotionFromMontagesOnly);
	}
	bAirAttack = false;
	SetActorRotation(FRotator(0.f, (-Away).Rotation().Yaw, 0.f));
	const float Dist = FVector::Dist2D(GetActorLocation(), From);
	const bool bNear = Dist < 750.f;
	// Shoved backward on its feet (Lucy_Avoid_B, slowed) whose root motion carries the push. No launch,
	// no knockdown, no damage.
	if (RoarHitAnim)
	{
		constexpr float Rate = 0.85f;
		StartStun(RoarHitAnim->GetPlayLength() / Rate * 0.9f, RoarHitAnim, Rate);
		SetAnimRootMotionTranslationScale(bNear ? 1.25f : 0.9f);
		LaunchCharacter(Away * (bNear ? 380.f : 180.f), true, false);
	}
	else
	{
		LaunchCharacter(Away * (bNear ? 650.f : 350.f), true, false);
		StartStun(0.55f, HitReactAnims.IsValidIndex(0) ? HitReactAnims[0].Get() : nullptr, 1.f);
	}
	// Dust burst under the feet and a pale shock ring on the body, a hard impact frame.
	const FVector Feet = GetActorLocation() - FVector(0.f, 0.f, GetCapsuleComponent()->GetScaledCapsuleHalfHeight() - 4.f);
	ABFRingFX::SpawnGround(GetWorld(), Feet, FLinearColor(0.75f, 0.7f, 0.6f), 30.f, 320.f, 0.45f);
	ABFRingFX::Spawn(GetWorld(), GetActorLocation() + FVector(0.f, 0.f, 40.f), BFCombat::BossMagicPale(), 20.f, 220.f, 0.3f);
	ImpactFrame();
	WorldSlowMo(0.3f, 0.32f);
	UE_LOG(LogTemp, Display, TEXT("BFTEST roar knockback dist=%.0f hp=%.0f anim=%s"), Dist, Health, RoarHitAnim ? TEXT("avoid_b") : TEXT("flinch"));
}

void ABFPlayerCharacter::StartBossCinematic(ABFEnemyBase* Boss, float Duration, float ImpactAt)
{
	if (!Boss || bClashCam)
	{
		return;
	}
	if (bGrabbed)
	{
		GrabStart -= 10.0; // let go now, without the drains still to come
		GrabTicks = 3;
		TickGrabbed();
	}
	const double Now = GetWorld()->GetRealTimeSeconds();
	bCinematic = true;
	CineStart = Now;
	CineDuration = Duration;
	CineBoss = Boss;
	CineImpactAt = ImpactAt > 0.f ? ImpactAt : Duration * 0.35f;
	bCineBraced = false;
	bCineImpact = false;
	bCineWideInit = false;
	CineOrbitDist = -1.f;
	bStompReady = false;
	Buffered = EBuffered::None;
	if (State == EBFPlayerState::Attacking || State == EBFPlayerState::Dashing || State == EBFPlayerState::Guarding)
	{
		if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
		{
			AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.30f), CurrentMontage);
		}
		EndAction();
	}
	GetCharacterMovement()->StopMovementImmediately();

	// Low shot in front of the boss, off to one side, looking up at him. The arena has pillars, so
	// try a ring of spots (front first) and keep the one with the clearest view of his whole body.
	const FVector BossLoc = Boss->GetActorLocation();
	const float H = Boss->GetHalfHeight();
	const FVector Fwd = Boss->GetActorForwardVector().GetSafeNormal2D();
	const FVector Pivot = BossLoc + FVector(0.f, 0.f, H * 0.5f);
	const float Dist = H * 3.f + 380.f;
	FCollisionQueryParams Params(SCENE_QUERY_STAT(BFCine), false, Boss);
	Params.AddIgnoredActor(this);
	const FCollisionShape Ball = FCollisionShape::MakeSphere(35.f);
	const FVector Probes[] = { BossLoc + FVector(0.f, 0.f, H * 0.8f), Pivot, BossLoc - FVector(0.f, 0.f, H * 0.5f) };
	FVector Cam = BossLoc + Fwd * Dist;
	float BestScore = -BIG_NUMBER;
	for (const float Yaw : { 0.f, 35.f, -35.f, 70.f, -70.f, 110.f, -110.f, 150.f, -150.f, 180.f })
	{
		const FVector Dir = Fwd.RotateAngleAxis(Yaw, FVector::UpVector);
		const FVector Side = FVector::CrossProduct(FVector::UpVector, Dir);
		for (const float Sign : { 1.f, -1.f })
		{
			FVector Try = BossLoc + Dir * Dist + Side * (H * 0.9f * Sign);
			Try.Z = BossLoc.Z - H + 110.f;
			float Score = -FMath::Abs(Yaw) / 60.f - (Sign < 0.f ? 0.1f : 0.f);
			FHitResult Block;
			if (GetWorld()->SweepSingleByChannel(Block, Pivot, Try, FQuat::Identity, ECC_Camera, Ball, Params))
			{
				// A wall in between: the camera would sit right in front of it, far too close.
				Score -= (1.f - Block.Time) * 6.f;
				Try = Block.Location;
			}
			for (const FVector& P : Probes)
			{
				if (GetWorld()->SweepTestByChannel(P, Try, FQuat::Identity, ECC_Camera, Ball, Params))
				{
					Score -= 2.f; // part of him hidden
				}
			}
			// The player standing in front of him: prefer an angle that puts us to one side.
			const FVector ToBoss2D = (Pivot - Try).GetSafeNormal2D();
			const FVector ToMe2D = (GetActorLocation() - Try).GetSafeNormal2D();
			const float Sep = FMath::RadiansToDegrees(FMath::Acos(FMath::Clamp(ToBoss2D | ToMe2D, -1.f, 1.f)));
			if (Sep < 12.f && FVector::Dist2D(GetActorLocation(), Try) < FVector::Dist2D(Pivot, Try))
			{
				Score -= 2.5f * (1.f - Sep / 12.f);
			}
			// Something close to the lens at the frame edges (a pillar filling half the shot).
			const FVector Look = (Pivot - Try).GetSafeNormal();
			for (const float Edge : { -20.f, 20.f })
			{
				FHitResult EdgeHit;
				const FVector EdgeEnd = Try + Look.RotateAngleAxis(Edge, FVector::UpVector) * Dist * 0.7f;
				if (GetWorld()->LineTraceSingleByChannel(EdgeHit, Try, EdgeEnd, ECC_Camera, Params))
				{
					Score -= (1.f - EdgeHit.Time) * 1.5f;
				}
			}
			if (Score > BestScore)
			{
				BestScore = Score;
				Cam = Try;
			}
		}
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST cinematic camera score=%.2f dist=%.0f"), BestScore, FVector::Dist2D(Cam, BossLoc));
	CineCamLoc = Cam;
	CineCamLook = BossLoc + FVector(0.f, 0.f, H * 0.6f);
	CineCamRot = (CineCamLook - Cam).Rotation();
	// Wide shot on the player goes to the open side of the boss-player line.
	{
		const FVector P = GetActorLocation();
		const FVector ToBoss = (BossLoc - P).GetSafeNormal2D();
		const FVector Side = FVector::CrossProduct(FVector::UpVector, ToBoss);
		float Room[2] = { 0.f, 0.f };
		for (int32 I = 0; I < 2; ++I)
		{
			FHitResult Hit;
			const FVector To = P + Side * (I == 0 ? 520.f : -520.f) - ToBoss * 200.f + FVector(0.f, 0.f, 120.f);
			Room[I] = GetWorld()->SweepSingleByChannel(Hit, P + FVector(0.f, 0.f, 60.f), To, FQuat::Identity, ECC_Camera, Ball, Params) ? Hit.Time : 1.f;
		}
		CineOrbitSign = Room[0] >= Room[1] ? 1.f : -1.f;
	}
	UE_LOG(LogTemp, Display, TEXT("BFTEST cinematic start dur=%.2f"), Duration);
}

float ABFPlayerCharacter::GetCinematicAlpha() const
{
	if (!bCinematic)
	{
		return 0.f;
	}
	const float T = static_cast<float>(GetWorld()->GetRealTimeSeconds() - CineStart);
	// Slow ease in from the gameplay camera, longer ease back out.
	return FMath::Min(FMath::SmoothStep(0.f, 0.6f, T), 1.f - FMath::SmoothStep(CineDuration - 0.9f, CineDuration, T));
}

float ABFPlayerCharacter::GetCinematicTitleAlpha() const
{
	if (!bCinematic)
	{
		return 0.f;
	}
	const float T = static_cast<float>(GetWorld()->GetRealTimeSeconds() - CineStart);
	return FMath::SmoothStep(CineImpactAt + 1.1f, CineImpactAt + 1.6f, T) * (1.f - FMath::SmoothStep(CineDuration - 0.8f, CineDuration - 0.25f, T));
}

void ABFPlayerCharacter::TickCinematic()
{
	const double Now = GetWorld()->GetRealTimeSeconds();
	const float T = static_cast<float>(Now - CineStart);
	if (T >= CineDuration)
	{
		bCinematic = false;
		FollowCamera->SetRelativeLocationAndRotation(CameraBaseOffset, FRotator::ZeroRotator);
		FollowCamera->SetFieldOfView(CameraBaseFov);
		ShakeAmplitude = 0.f;
		UE_LOG(LogTemp, Display, TEXT("BFTEST cinematic end"));
		return;
	}
	const float RealDelta = FApp::GetDeltaTime();
	const float A = GetCinematicAlpha();
	ABFEnemyBase* Boss = CineBoss.Get();
	FVector BossLoc = Boss ? Boss->GetActorLocation() : GetActorLocation() + GetActorForwardVector() * 500.f;
	const float H = Boss ? Boss->GetHalfHeight() : 145.f;
	// The roar clip leaps without root motion: the body lands well away from the capsule. Frame the
	// body (pelvis), on the capsule's floor height.
	FVector BossBody = BossLoc;
	if (Boss && Boss->GetMesh() && Boss->GetMesh()->GetBoneIndex(TEXT("pelvis")) != INDEX_NONE)
	{
		BossBody = Boss->GetMesh()->GetBoneLocation(TEXT("pelvis"));
		BossLoc = FVector(BossBody.X, BossBody.Y, BossLoc.Z);
	}
	const FVector BossChest = BossLoc + FVector(0.f, 0.f, H * 0.45f);
	const FVector Me = GetActorLocation();
	const FVector ToBoss = (BossLoc - Me).GetSafeNormal2D();
	FCollisionQueryParams Params(SCENE_QUERY_STAT(BFCineTick), false, this);
	if (Boss)
	{
		Params.AddIgnoredActor(Boss);
	}
	const FCollisionShape Ball = FCollisionShape::MakeSphere(25.f);
	auto Clear = [&](const FVector& From, const FVector& To)
	{
		FHitResult Hit;
		return GetWorld()->SweepSingleByChannel(Hit, From, To, FQuat::Identity, ECC_Camera, Ball, Params) ? Hit.Location : To;
	};

	// Beats. The player braces against the roar; the roar itself (boss side) staggers him.
	if (!bCineBraced && T >= CineImpactAt - 0.75f)
	{
		bCineBraced = true;
		if (State == EBFPlayerState::Free && !GetCharacterMovement()->IsFalling() && GuardAnim)
		{
			SetActorRotation(FRotator(0.f, ToBoss.Rotation().Yaw, 0.f));
			PlayAnim(GuardAnim, 1.1f, 0.15f, 0.1f);
		}
	}
	if (!bCineImpact && T >= CineImpactAt)
	{
		bCineImpact = true;
		UE_LOG(LogTemp, Display, TEXT("BFTEST cinematic shot wide t=%.2f"), T);
	}

	// Shot 1: low angle on the boss, slow push-in with a slight drift, tightening the lens.
	const float U1 = FMath::Clamp(T / FMath::Max(CineImpactAt, 0.1f), 0.f, 1.f);
	CineCamLook = FMath::VInterpTo(CineCamLook, FVector(BossLoc.X, BossLoc.Y, FMath::Max(BossLoc.Z + H * 0.6f, BossBody.Z + H * 0.4f)), RealDelta, 6.f);
	const FVector Look1Dir = (CineCamLook - CineCamLoc).GetSafeNormal();
	const FVector Drift = FVector::CrossProduct(FVector::UpVector, Look1Dir).GetSafeNormal() * CineOrbitSign;
	FVector Loc1 = CineCamLoc + Look1Dir * (FMath::SmoothStep(0.f, 1.f, U1) * 170.f) + Drift * (U1 * 50.f);
	{
		// He leaps toward the lens: keep a minimum distance from where he is now.
		const float MinDist = H * 2.f + 300.f;
		const FVector Off = FVector(Loc1.X - BossLoc.X, Loc1.Y - BossLoc.Y, 0.f);
		if (Off.Size() < MinDist)
		{
			const FVector Want = BossLoc + Off.GetSafeNormal() * MinDist;
			Loc1 = Clear(BossChest, FVector(Want.X, Want.Y, Loc1.Z));
		}
	}
	const FQuat Rot1 = (CineCamLook - Loc1).Rotation().Quaternion();
	constexpr float Fov1 = 62.f;

	// Shot 2: side-on wide shot of the player taking the roar, the boss in the back of the frame.
	const FVector Side = FVector::CrossProduct(FVector::UpVector, ToBoss) * CineOrbitSign;
	const FVector WideWant = Clear(Me + FVector(0.f, 0.f, 60.f), Me + Side * 480.f - ToBoss * 200.f + FVector(0.f, 0.f, 150.f));
	const FVector WideLookWant = FMath::Lerp(Me + FVector(0.f, 0.f, 60.f), BossChest, 0.4f);
	if (!bCineWideInit)
	{
		bCineWideInit = true;
		CineWideLoc = WideWant;
		CineWideLook = WideLookWant;
	}
	CineWideLoc = FMath::VInterpTo(CineWideLoc, WideWant, RealDelta, 3.5f);
	CineWideLook = FMath::VInterpTo(CineWideLook, WideLookWant, RealDelta, 5.f);
	const FQuat Rot2 = (CineWideLook - CineWideLoc).Rotation().Quaternion();
	constexpr float Fov2 = 76.f;

	// Shot 3: slow low orbit around the boss for the title card, starting on the player's side.
	if (CineOrbitDist < 0.f && T >= CineImpactAt + 0.8f)
	{
		CineOrbitDist = H * 2.4f + 320.f;
		// Start square to the boss-player line and turn away from the player, so he never fills the lens.
		const float BaseYaw = (Me - BossLoc).Rotation().Yaw + 100.f * CineOrbitSign;
		CineOrbitYaw = BaseYaw;
		for (const float Off : { 0.f, 35.f, -35.f, 70.f, -70.f, 110.f, -110.f })
		{
			const FVector Dir = FRotator(0.f, BaseYaw + Off, 0.f).Vector();
			FHitResult Hit;
			if (!GetWorld()->SweepSingleByChannel(Hit, BossChest, BossChest + Dir * CineOrbitDist, FQuat::Identity, ECC_Camera, Ball, Params))
			{
				CineOrbitYaw = BaseYaw + Off;
				break;
			}
		}
		UE_LOG(LogTemp, Display, TEXT("BFTEST cinematic shot orbit t=%.2f yaw=%.0f"), T, CineOrbitYaw);
	}
	if (CineOrbitDist > 0.f)
	{
		CineOrbitYaw += 14.f * CineOrbitSign * RealDelta;
	}
	const FVector OrbitDir = FRotator(0.f, CineOrbitYaw, 0.f).Vector();
	const FVector Loc3 = Clear(BossChest, BossLoc + OrbitDir * FMath::Max(CineOrbitDist, 300.f) + FVector(0.f, 0.f, -H * 0.35f));
	const FQuat Rot3 = (BossLoc + FVector(0.f, 0.f, H * 0.55f) - Loc3).Rotation().Quaternion();
	constexpr float Fov3 = 56.f;

	// Eased blends between the shots: a quick pull-back on the roar, a slow drift into the orbit.
	const float W2 = FMath::SmoothStep(CineImpactAt - 0.05f, CineImpactAt + 0.42f, T);
	const float W3 = CineOrbitDist > 0.f ? FMath::SmoothStep(CineImpactAt + 1.0f, CineImpactAt + 1.7f, T) : 0.f;
	// Camera moves swing around him (angle, distance and height about the boss blended separately): a
	// straight blend between shots on opposite sides of him cut right through his body.
	auto ArcLerp = [&BossLoc](const FVector& From, const FVector& To, float W)
	{
		if (W <= 0.f)
		{
			return From;
		}
		if (W >= 1.f)
		{
			return To;
		}
		const FVector DA = From - BossLoc;
		const FVector DB = To - BossLoc;
		const float YawA = DA.Rotation().Yaw;
		const float Yaw = YawA + FMath::FindDeltaAngleDegrees(YawA, DB.Rotation().Yaw) * W;
		const float Dist = FMath::Lerp(DA.Size2D(), DB.Size2D(), W);
		return BossLoc + FRotator(0.f, Yaw, 0.f).Vector() * Dist + FVector(0.f, 0.f, FMath::Lerp(DA.Z, DB.Z, W));
	};
	FVector Loc = ArcLerp(ArcLerp(Loc1, CineWideLoc, W2), Loc3, W3);
	const FQuat Rot = FQuat::Slerp(FQuat::Slerp(Rot1, Rot2, W2), Rot3, W3);
	const float Fov = FMath::Lerp(FMath::Lerp(Fov1, Fov2, W2), Fov3, W3);
	CineCamRot = Rot.Rotator();

	// The gameplay camera turns to frame the boss behind the player, so the blend back lands on a good view.
	if (Controller && T >= CineImpactAt)
	{
		const FRotator Want((BossChest - (Me + FVector(0.f, 0.f, 120.f))).Rotation().Pitch - 8.f, ToBoss.Rotation().Yaw, 0.f);
		Controller->SetControlRotation(FMath::RInterpTo(Controller->GetControlRotation(), Want, RealDelta, 2.5f));
	}

	if (ShakeTime < ShakeDuration)
	{
		ShakeTime += RealDelta;
		const float F = FMath::Clamp(1.f - ShakeTime / ShakeDuration, 0.f, 1.f);
		Loc += FMath::VRand() * ShakeAmplitude * F * F;
	}
	const FTransform Socket = CameraBoom->GetSocketTransform(USpringArmComponent::SocketName);
	const FVector BaseLoc = Socket.TransformPosition(CameraBaseOffset);
	const FQuat BaseRot = Socket.GetRotation();
	FollowCamera->SetWorldLocationAndRotation(ArcLerp(BaseLoc, Loc, A), FQuat::Slerp(BaseRot, Rot, A));
	FollowCamera->SetFieldOfView(FMath::Lerp(CameraBaseFov, Fov, A));
}

void ABFPlayerCharacter::WorldSlowMo(float Dilation, float RealSeconds)
{
	if (bClashCam || bStruggle)
	{
		return; // the clash cinematic owns time
	}
	const double Now = GetWorld()->GetRealTimeSeconds();
	if (SlowMoEnd > Now)
	{
		Dilation = FMath::Min(Dilation, UGameplayStatics::GetGlobalTimeDilation(this));
	}
	UGameplayStatics::SetGlobalTimeDilation(this, Dilation);
	SlowMoEnd = FMath::Max(SlowMoEnd, Now + RealSeconds);
}

void ABFPlayerCharacter::ImpactFrame()
{
	ImpactFrameTime = GetWorld()->GetRealTimeSeconds();
	if (ImpactVolume)
	{
		ImpactVolume->BlendWeight = 1.f;
	}
}

void ABFPlayerCharacter::UpdateSwordTrail()
{
	if (!SwordTrail)
	{
		return;
	}
	bool bOn = State == EBFPlayerState::Stomping || State == EBFPlayerState::Plunging;
	if (State == EBFPlayerState::Attacking)
	{
		const UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
		const TArray<FBFAttackDef>& Defs = GetChainDefs(CurrentChain);
		if (AnimInstance && CurrentMontage && Defs.IsValidIndex(ComboIndex))
		{
			const float Pos = AnimInstance->Montage_GetPosition(CurrentMontage);
			for (const FBFHitWindow& W : Defs[ComboIndex].Windows)
			{
				bOn |= Pos >= W.Start - 0.07f && Pos <= W.End + 0.05f;
			}
		}
	}
	bSwordSmearOn = bOn;
	if (bOn && !SwordTrail->IsActive())
	{
		SwordTrail->Activate(true);
	}
	else if (!bOn && SwordTrail->IsActive())
	{
		SwordTrail->Deactivate();
	}
}

