	template <typename T>
	T* FindAsset(const FString& Path)
	{
		ConstructorHelpers::FObjectFinder<T> Finder(*Path);
		return Finder.Succeeded() ? Finder.Object : nullptr;
	}

	UAnimSequence* FindAnim(const TCHAR* Name)
	{
		return FindAsset<UAnimSequence>(FString::Printf(TEXT("%s%s.%s"), BFPaths::AnimDir, Name, Name));
	}

	FBFAttackDef MakeAttack(const TCHAR* Anim, std::initializer_list<FBFHitWindow> Windows, float Cancel, float Damage, float Posture, float Rate, bool bFinisher)
	{
		FBFAttackDef Def;
		Def.AnimPath = Anim;
		Def.Windows = Windows;
		Def.CancelTime = Cancel;
		Def.Damage = Damage;
		Def.PostureDamage = Posture;
		Def.PlayRate = Rate;
		Def.bFinisher = bFinisher;
		return Def;
	}

