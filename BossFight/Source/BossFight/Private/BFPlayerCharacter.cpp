void ABFPlayerCharacter::BuildInput()
{
	if (MappingContext)
	{
		return;
	}

	MappingContext = NewObject<UInputMappingContext>(this, TEXT("IMC_Player"));

	auto MakeAction = [this](const TCHAR* Name, EInputActionValueType Type)
	{
		UInputAction* Action = NewObject<UInputAction>(this, Name);
		Action->ValueType = Type;
		return Action;
	};
	MoveAction = MakeAction(TEXT("IA_Move"), EInputActionValueType::Axis2D);
	LookAction = MakeAction(TEXT("IA_Look"), EInputActionValueType::Axis2D);
	JumpAction = MakeAction(TEXT("IA_Jump"), EInputActionValueType::Boolean);
	LightAction = MakeAction(TEXT("IA_Light"), EInputActionValueType::Boolean);
	HeavyAction = MakeAction(TEXT("IA_Heavy"), EInputActionValueType::Boolean);
	DashAction = MakeAction(TEXT("IA_Dash"), EInputActionValueType::Boolean);
	SprintAction = MakeAction(TEXT("IA_Sprint"), EInputActionValueType::Boolean);
	GuardAction = MakeAction(TEXT("IA_Guard"), EInputActionValueType::Boolean);
	LockAction = MakeAction(TEXT("IA_LockOn"), EInputActionValueType::Boolean);
	LockSwitchAction = MakeAction(TEXT("IA_LockSwitch"), EInputActionValueType::Axis1D);

	// WASD into one 2D vector: X = right, Y = forward.
	auto MapMoveKey = [this](const FKey& Key, bool bSwizzle, bool bNegate)
	{
		FEnhancedActionKeyMapping& Mapping = MappingContext->MapKey(MoveAction, Key);
		if (bSwizzle)
		{
			Mapping.Modifiers.Add(NewObject<UInputModifierSwizzleAxis>(MappingContext));
		}
		if (bNegate)
		{
			Mapping.Modifiers.Add(NewObject<UInputModifierNegate>(MappingContext));
		}
	};
	MapMoveKey(EKeys::W, true, false);
	MapMoveKey(EKeys::S, true, true);
	MapMoveKey(EKeys::D, false, false);
	MapMoveKey(EKeys::A, false, true);
	MappingContext->MapKey(MoveAction, EKeys::Gamepad_Left2D);

	// Mouse Y goes up when the mouse moves up; invert it so pushing up looks up.
	FEnhancedActionKeyMapping& MouseLook = MappingContext->MapKey(LookAction, EKeys::Mouse2D);
	UInputModifierNegate* InvertY = NewObject<UInputModifierNegate>(MappingContext);
	InvertY->bX = false;
	InvertY->bY = true;
	InvertY->bZ = false;
	MouseLook.Modifiers.Add(InvertY);
	MappingContext->MapKey(LookAction, EKeys::Gamepad_Right2D);

	MappingContext->MapKey(JumpAction, EKeys::SpaceBar);
	MappingContext->MapKey(JumpAction, EKeys::Gamepad_FaceButton_Bottom);
	MappingContext->MapKey(LightAction, EKeys::LeftMouseButton);
	MappingContext->MapKey(LightAction, EKeys::Gamepad_FaceButton_Left);
	// Mouse: hold the left button for a heavy (OnLightDown / TickLightHold); the pad keeps a heavy button.
	MappingContext->MapKey(HeavyAction, EKeys::Gamepad_FaceButton_Top);
	MappingContext->MapKey(DashAction, EKeys::RightMouseButton);
	MappingContext->MapKey(DashAction, EKeys::Gamepad_FaceButton_Right);
	MappingContext->MapKey(SprintAction, EKeys::LeftShift);
	MappingContext->MapKey(SprintAction, EKeys::Gamepad_LeftThumbstick);
	MappingContext->MapKey(GuardAction, EKeys::F);
	MappingContext->MapKey(GuardAction, EKeys::Gamepad_LeftShoulder);
	// Lock-on: middle mouse / right stick click; mouse wheel (or d-pad) switches target.
	MappingContext->MapKey(LockAction, EKeys::MiddleMouseButton);
	MappingContext->MapKey(LockAction, EKeys::Gamepad_RightThumbstick);
	MappingContext->MapKey(LockSwitchAction, EKeys::MouseWheelAxis);
	MappingContext->MapKey(LockSwitchAction, EKeys::Gamepad_DPad_Right);
	FEnhancedActionKeyMapping& PadLeft = MappingContext->MapKey(LockSwitchAction, EKeys::Gamepad_DPad_Left);
	PadLeft.Modifiers.Add(NewObject<UInputModifierNegate>(MappingContext));
}

void ABFPlayerCharacter::SetupPlayerInputComponent(UInputComponent* PlayerInputComponent)
{
	Super::SetupPlayerInputComponent(PlayerInputComponent);

	BuildInput();
	// Automated runs drive the handlers directly; stray keys or mouse moves (the window grabs focus
	// while someone types elsewhere) must not leak into them.
	if (FParse::Param(FCommandLine::Get(), TEXT("BFAutoTest")) || FCString::Strifind(FCommandLine::Get(), TEXT("-BFAutoTest=")))
	{
		return;
	}
	if (UEnhancedInputComponent* Input = Cast<UEnhancedInputComponent>(PlayerInputComponent))
	{
		Input->BindAction(MoveAction, ETriggerEvent::Triggered, this, &ABFPlayerCharacter::Move);
		Input->BindAction(LookAction, ETriggerEvent::Triggered, this, &ABFPlayerCharacter::Look);
		Input->BindAction(JumpAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnJumpPressed);
		Input->BindAction(JumpAction, ETriggerEvent::Completed, this, &ACharacter::StopJumping);
		Input->BindAction(LightAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnLightDown);
		Input->BindAction(LightAction, ETriggerEvent::Completed, this, &ABFPlayerCharacter::OnLightUp);
		Input->BindAction(SprintAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnSprintPressed);
		Input->BindAction(SprintAction, ETriggerEvent::Completed, this, &ABFPlayerCharacter::OnSprintReleased);
		Input->BindAction(HeavyAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnHeavyPressed);
		Input->BindAction(DashAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnDashPressed);
		Input->BindAction(GuardAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnGuardPressed);
		Input->BindAction(GuardAction, ETriggerEvent::Completed, this, &ABFPlayerCharacter::OnGuardReleased);
		Input->BindAction(LockAction, ETriggerEvent::Started, this, &ABFPlayerCharacter::OnLockPressed);
		Input->BindAction(LockSwitchAction, ETriggerEvent::Triggered, this, &ABFPlayerCharacter::OnLockSwitch);
	}
}

void ABFPlayerCharacter::Move(const FInputActionValue& Value)
{
	const FVector2D Axis = Value.Get<FVector2D>();
	if (!Controller || State == EBFPlayerState::Clashing || bCinematic || bGrabbed)
	{
		return;
	}

	const FRotator YawRotation(0.f, Controller->GetControlRotation().Yaw, 0.f);
	const FVector Forward = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::X);
	const FVector Right = FRotationMatrix(YawRotation).GetUnitAxis(EAxis::Y);
	const FVector World = Forward * Axis.Y + Right * Axis.X;
	if (!World.IsNearlyZero())
	{
		LastMoveInput = World.GetSafeNormal2D();
		LastMoveInputTime = GetWorld()->GetRealTimeSeconds();
	}

	// Attacks and dashes drive the body with root motion; input only steers the next action.
	if (State == EBFPlayerState::Free)
	{
		AddMovementInput(Forward, Axis.Y);
		AddMovementInput(Right, Axis.X);
	}
}

void ABFPlayerCharacter::Look(const FInputActionValue& Value)
{
	const FVector2D Axis = Value.Get<FVector2D>();
	if (bLockedOn || bCinematic || MagicCamAlpha > 0.05f)
	{
		return; // the lock-on / cutscene / spell camera aims itself
	}
	AddControllerYawInput(Axis.X);
	AddControllerPitchInput(Axis.Y);
}

void ABFPlayerCharacter::OnJumpPressed()
{
	if (bCinematic || bGrabbed)
	{
		return;
	}
	if (State == EBFPlayerState::Free)
	{
		Jump();
		return;
	}
	// Ground swing: jump cuts its recovery (or the rest of it once it connected) like the dash
	// does; pressed inside an open hit window that has not connected, it fires once that closes.
	if (State == EBFPlayerState::Attacking && !bAirAttack && !GetCharacterMovement()->IsFalling())
	{
		if (CanCancelAttack())
		{
			CancelAttackIntoJump();
			return;
		}
		Buffered = EBuffered::Jump;
		BufferedTime = GetWorld()->GetRealTimeSeconds();
	}
}

void ABFPlayerCharacter::CancelAttackIntoJump()
{
	const bool bAfterConnect = ActiveWindow != INDEX_NONE;
	Buffered = EBuffered::None;
	if (UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance())
	{
		AnimInstance->Montage_StopWithBlendSettings(BFAnimBlend::Inert(0.15f), CurrentMontage);
	}
	EndAction();
	if (State == EBFPlayerState::Free)
	{
		Jump();
		UE_LOG(LogTemp, Display, TEXT("BFTEST cancel jump connect=%d"), bAfterConnect ? 1 : 0);
	}
}

void ABFPlayerCharacter::OnLightPressed()
{
	if (bCinematic || bGrabbed)
	{
		return;
	}
	if (CanStomp())
	{
		// Jumped a ground wave: drop onto the boss's head.
		StartStomp();
		return;
	}
	if (GetCharacterMovement()->IsFalling())
	{
		// Air combo: once per jump, its first swing pays a dodge charge.
		if (State == EBFPlayerState::Free && !bAirComboUsed && TryPayAirCharge())
		{
			StartAirAttack(0);
		}
		return;
	}
	if (bAirAttack)
	{
		Buffered = EBuffered::Light; // next hovering swing
		BufferedTime = GetWorld()->GetRealTimeSeconds();
		return;
	}
	if (TryExecution())
	{
		return;
	}
	if (State == EBFPlayerState::Free || State == EBFPlayerState::Guarding)
	{
		StartAttack(EBFChain::Light, 0);
		return;
	}
	Buffered = EBuffered::Light;
	BufferedTime = GetWorld()->GetRealTimeSeconds();
}

void ABFPlayerCharacter::OnHeavyPressed()
{
	if (bCinematic || bGrabbed)
	{
		return;
	}
	// Plunge: heavy in the air (jumping, or out of the air combo) dives onto the ground below.
	const bool bAirborne = GetCharacterMovement()->IsFalling() && State == EBFPlayerState::Free;
	const bool bFromAirCombo = bAirAttack && State == EBFPlayerState::Attacking && CanCancelAttack();
	if (bAirborne || bFromAirCombo)
	{
		if (TryPayAirCharge())
		{
			StartPlunge();
		}
		return;
	}
	if (bAirAttack)
	{
		Buffered = EBuffered::Heavy;
		BufferedTime = GetWorld()->GetRealTimeSeconds();
		return;
	}
	if (GetCharacterMovement()->IsFalling())
	{
		return;
	}
	if (TryExecution())
	{
		return;
	}
	if (State == EBFPlayerState::Free || State == EBFPlayerState::Guarding)
	{
		StartAttack(EBFChain::Heavy, 0);
		return;
	}
	Buffered = EBuffered::Heavy;
	BufferedTime = GetWorld()->GetRealTimeSeconds();
}

void ABFPlayerCharacter::OnDashPressed()
{
	if (bCinematic || bGrabbed || State == EBFPlayerState::Plunging)
	{
		return;
	}
	if (GetCharacterMovement()->IsFalling() || bAirAttack)
	{
		// No air dash: in the air the dash button plunges (same rules as a held heavy).
		if (State == EBFPlayerState::Free || bAirAttack)
		{
			OnHeavyPressed();
		}
		return;
	}
	if (State == EBFPlayerState::Free || State == EBFPlayerState::Guarding)
	{
		State = EBFPlayerState::Free;
		StartDash();
		return;
	}
	// Mid-swing and already cancellable (between hit windows, or the swing connected): roll right
	// away instead of waiting a tick for the buffer, so the cancel feels instant.
	if (State == EBFPlayerState::Attacking && CanCancelAttack())
	{
		const bool bAfterConnect = ActiveWindow != INDEX_NONE;
		StartDash();
		if (State == EBFPlayerState::Dashing)
		{
			if (bAfterConnect)
			{
				UE_LOG(LogTemp, Display, TEXT("BFTEST cancel dash after connect"));
			}
			return;
		}
	}
	Buffered = EBuffered::Dash;
	BufferedTime = GetWorld()->GetRealTimeSeconds();
}

void ABFPlayerCharacter::OnLightDown()
{
	if (State == EBFPlayerState::Clashing)
	{
		// Strength clash: mash the attack button (the guard key still works too).
		bLightHeld = false;
		StrugglePress();
		return;
	}
	if (bCinematic || bGrabbed)
	{
		return;
	}
	bLightHeld = true;
	bLightHeavyFired = false;
	LightDownTime = GetWorld()->GetRealTimeSeconds();
	// Timing-critical presses act at once instead of waiting to tell a tap from a hold.
	if (CanStomp())
	{
		StartStomp();
		bLightHeavyFired = true;
	}
	else if (!GetCharacterMovement()->IsFalling() && TryExecution())
	{
		bLightHeavyFired = true;
	}
}

void ABFPlayerCharacter::OnLightUp()
{
	const bool bTap = bLightHeld && !bLightHeavyFired;
	bLightHeld = false;
	if (bTap)
	{
		OnLightPressed();
	}
}

void ABFPlayerCharacter::TickLightHold()
{
	if (bLightHeld && !bLightHeavyFired && GetWorld()->GetRealTimeSeconds() - LightDownTime >= LightHoldForHeavy)
	{
		bLightHeavyFired = true;
		UE_LOG(LogTemp, Display, TEXT("BFTEST hold heavy"));
		OnHeavyPressed();
	}
}

void ABFPlayerCharacter::OnSprintPressed()
{
	bSprintHeld = true;
}

void ABFPlayerCharacter::OnSprintReleased()
{
	bSprintHeld = false;
}

void ABFPlayerCharacter::TickSprint(float DeltaSeconds)
{
	UCharacterMovementComponent* Movement = GetCharacterMovement();
	const bool bWant = bSprintHeld && State == EBFPlayerState::Free && Movement->IsMovingOnGround() && HasRecentMoveInput()
		&& !bCinematic && !bGrabbed;
	UBFAnimInstance* Anim = Cast<UBFAnimInstance>(GetMesh()->GetAnimInstance());
	if (bWant)
	{
		// Running ignores the lock-on strafe: face the run direction at full speed.
		Movement->MaxWalkSpeed = SprintSpeed;
		Movement->bOrientRotationToMovement = true;
		if (Anim)
		{
			Anim->bStrafing = false;
		}
	}
	else if (bSprinting)
	{
		Movement->MaxWalkSpeed = bLockedOn ? 427.f : BaseWalkSpeed;
		Movement->bOrientRotationToMovement = !bLockedOn;
		if (Anim)
		{
			Anim->bStrafing = bLockedOn;
		}
	}
	if (bWant != bSprinting)
	{
		UE_LOG(LogTemp, Display, TEXT("BFTEST sprint %s"), bWant ? TEXT("on") : TEXT("off"));
	}
	bSprinting = bWant;
}

void ABFPlayerCharacter::TickSmears()
{
	if (SwordSmear)
	{
		if (bSwordSmearOn)
		{
			// Inner edge a quarter up the blade, outer edge just past the tip.
			const FTransform& X = Sword->GetComponentTransform();
			const FVector Tip = X.TransformPosition(BladeLocalA);
			const FVector Pommel = X.TransformPosition(BladeLocalB);
			SwordSmear->AddSample(FMath::Lerp(Pommel, Tip, 0.25f), Tip + (Tip - Pommel) * 0.06f);
		}
		else
		{
			SwordSmear->Cut();
		}
	}
	if (SpeedStreaks.Num() == 0)
	{
		return;
	}
	// Strong streaks during the dash's fast part, faint ones while sprinting.
	float Strength = 0.f;
	if (State == EBFPlayerState::Dashing)
	{
		const UAnimInstance* AnimInstance = GetMesh()->GetAnimInstance();
		const float Pos = AnimInstance && CurrentMontage ? AnimInstance->Montage_GetPosition(CurrentMontage) : 0.f;
		Strength = Pos < DashGhostEnd + 0.1f ? 1.f : 0.f;
	}
	else if (bSprinting && GetVelocity().Size2D() > 600.f)
	{
		Strength = 0.6f;
	}
	// -BFNoDashVFX: bare animation, no speed streaks either.
	static const bool bNoDashVfx = FParse::Param(FCommandLine::Get(), TEXT("BFNoDashVFX"));
	if (bNoDashVfx)
	{
		Strength = 0.f;
	}
	if (!FMath::IsNearlyEqual(Strength, StreakStrength))
	{
		StreakStrength = Strength;
		for (UBFSmearTrail* Streak : SpeedStreaks)
		{
			if (Strength > 0.f)
			{
				Streak->SetLook(FLinearColor(0.45f, 0.85f, 1.f), 5.f * Strength, Strength >= 1.f ? 0.22f : 0.16f);
			}
		}
	}
	static const FName Bones[] = { TEXT("head"), TEXT("spine_03"), TEXT("hand_l"), TEXT("hand_r"), TEXT("foot_l"), TEXT("foot_r") };
	const FVector Vel = GetVelocity();
	FVector Side = FVector::CrossProduct(Vel, FollowCamera->GetForwardVector()).GetSafeNormal();
	if (Side.IsNearlyZero())
	{
		Side = FVector::UpVector;
	}
	const float HalfWidth = Strength >= 1.f ? 5.f : 3.f;
	for (int32 I = 0; I < SpeedStreaks.Num() && I < UE_ARRAY_COUNT(Bones); ++I)
	{
		if (Strength <= 0.f || Vel.Size2D() < 200.f)
		{
			SpeedStreaks[I]->Cut();
			continue;
		}
		const FVector P = GetMesh()->GetBoneLocation(Bones[I]);
		SpeedStreaks[I]->AddSample(P - Side * HalfWidth, P + Side * HalfWidth);
	}
}

bool ABFPlayerCharacter::HasRecentMoveInput() const
{
	return GetWorld()->GetRealTimeSeconds() - LastMoveInputTime < 0.1;
}

